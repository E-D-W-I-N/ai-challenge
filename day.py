"""День 06 — агент как отдельная сущность: память против её отсутствия.

День 6 проверяет не модель, а архитектуру: агент должен быть классом, который
инстанцируют много раз с разными конфигами внутри одного процесса. Поэтому
сценарий дня сравнивает не модели, а **агентность**.

Обе колонки — одна и та же модель, один и тот же системный промпт, один и тот же
первый вопрос. Различается ровно одно поле конфига — `history_limit`:

* «С памятью» — окно 20 сообщений: агент помнит весь разговор;
* «Без памяти» — окно 0: каждый вопрос уходит в модель как первый.

На первом вопросе колонки неотличимы — это и есть контрольная точка. Разница
появляется со второго вопроса, который задают уже руками, прямо в колонке:
агент с памятью знает город, даты, бюджет и ограничение по еде, а агент без
памяти переспрашивает, потому что для него разговор начался только что.

Ростер `AGENTS` — собеседники дня на главном экране. Оттуда же командой
`/прогон` спавнятся субагенты по колонкам этого сценария.
"""

from __future__ import annotations

from app.schema import AgentSpec, Scenario

# Одна модель на обе колонки: разницу должна давать память, а не ступень.
# Дешёвая и быстрая — за прогон делается один вызов на колонку, а дальше
# разговор идёт руками, и каждый ручной вопрос тоже стоит денег.
MODEL = "openai/gpt-4o-mini"

TEMPERATURE = 0.3
"""Пониже: сравниваем содержание ответов, а не разброс формулировок."""

MAX_TOKENS = 700
"""Ответ должен помещаться в кадр рядом с соседней колонкой."""

SYSTEM = (
    "Ты — помощник по планированию поездок. Отвечай по-русски, коротко, "
    "обычным текстом без markdown-разметки: без звёздочек, решёток и таблиц. "
    "Если тебе не хватает данных о поездке, не выдумывай их — прямо скажи, "
    "чего ты не знаешь, и спроси об этом."
)

FIRST_QUESTION = (
    "Меня зовут Нина. Еду в Казань на три дня в середине октября, "
    "бюджет на всё — 20 000 рублей, я вегетарианка и не вожу машину. "
    "Набросай план поездки по дням."
)

FOLLOW_UPS = [
    "Что мне взять из одежды?",
    "Где поужинать в первый вечер и сколько это будет стоить?",
]
"""Второй и третий вопросы задаются руками, прямо в колонке, после «Старта».

Именно на них разница и видна: агент с памятью отвечает про октябрьскую Казань,
вегетарианское меню и остаток бюджета, а агент без памяти переспрашивает, куда
и когда едут, — для него это первое сообщение в разговоре.
"""

MESSAGES = [
    {"role": "system", "content": SYSTEM},
    {"role": "user", "content": FIRST_QUESTION},
]

WITH_MEMORY = 20
"""Окно памяти в сообщениях: десять обменов. Хватает на весь разговор дня."""

WITHOUT_MEMORY = 0
"""Ноль — агент без памяти: в модель уходит только системный промпт и вопрос."""


def traveller(label: str, history_limit: int, note: str) -> AgentSpec:
    """Колонка сценария. Отличается от соседней только полем history_limit."""
    return AgentSpec(
        label=label,
        model=MODEL,
        messages=MESSAGES,
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        history_limit=history_limit,
        note=note,
    )


# Собеседники главного экрана. Их создаёт стенд на старте процесса; командой
# «/прогон» они спавнят субагентов по колонкам сценария.
AGENTS = [
    AgentSpec(
        label="Ассистент",
        model=MODEL,
        messages=[],
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        history_limit=WITH_MEMORY,
        system=(
            "Ты — агент стенда AI-челленджа. Отвечай по-русски, коротко и по делу, "
            "обычным текстом без markdown-разметки. Ты помнишь этот разговор целиком. "
            "Прогон сценария запускается командой /прогон — она выполняется стендом, "
            "а не тобой; своими словами её не имитируй."
        ),
        note="Собеседник по умолчанию. Помнит разговор, умеет команду /прогон.",
    ),
    AgentSpec(
        label="Ассистент без памяти",
        model=MODEL,
        messages=[],
        temperature=TEMPERATURE,
        max_tokens=MAX_TOKENS,
        history_limit=WITHOUT_MEMORY,
        system=(
            "Ты — агент стенда AI-челленджа. Отвечай по-русски, коротко и по делу, "
            "обычным текстом без markdown-разметки."
        ),
        note="Тот же конфиг, но history_limit=0: каждый вопрос для него первый.",
    ),
]


SCENARIOS = [
    Scenario(
        title="Агент с памятью против агента без памяти",
        description=(
            "Две колонки — один и тот же агент с одним отличием в конфиге: "
            f"у левой окно памяти {WITH_MEMORY} сообщений, у правой — "
            f"{WITHOUT_MEMORY}. Модель, системный промпт, temperature={TEMPERATURE} "
            f"и max_tokens={MAX_TOKENS} совпадают, поэтому разницу можно приписать "
            "только памяти. Первый вопрос обеим колонкам одинаковый: Нина едет "
            "в Казань на три дня в середине октября, бюджет 20 000 рублей, "
            "вегетарианка, без машины — нужен план по дням. На этом вопросе "
            "колонки обязаны быть неотличимы: разговор только начался, и помнить "
            "ещё нечего. Разницу показывают следующие вопросы, которые задают "
            "руками прямо в колонке: «Что мне взять из одежды?» и «Где поужинать "
            "в первый вечер и сколько это будет стоить?». Историю диалога хранит "
            "сам агент на сервере, браузер её не отправляет."
        ),
        layout="split",
        # Вопросы про первый обмен: судья вызывается сразу после колонок, до
        # ручных вопросов, и судить ему пока нечего, кроме контрольной точки.
        # Это и есть его работа здесь — подтвердить, что до второго вопроса
        # колонки неотличимы, и разница дальше будет от памяти, а не от модели.
        judge_questions=[
            "Обе колонки получили один и тот же первый вопрос, одну модель и один "
            "системный промпт. Совпадают ли их ответы по сути — город, даты, "
            "число дней, бюджет, вегетарианское питание, отсутствие машины?",
            "Есть ли в ответах что-то, что нельзя объяснить конфигом колонок, — "
            "выдуманные факты о поездке, которых не было в вопросе?",
            "Короткий вывод: можно ли на этом первом обмене отличить агента "
            "с памятью от агента без памяти, и почему?",
        ],
        sessions=[
            traveller(
                "С памятью · окно 20",
                WITH_MEMORY,
                "history_limit=20: агент помнит весь разговор. Второй вопрос он "
                "поймёт без повторения условий поездки.",
            ),
            traveller(
                "Без памяти · окно 0",
                WITHOUT_MEMORY,
                "history_limit=0: в модель уходит только системный промпт и текущий "
                "вопрос. Со второго вопроса начнёт переспрашивать.",
            ),
        ],
    ),
]
