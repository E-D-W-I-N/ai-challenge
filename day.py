            "честно сказать, что не знает, и переспросить. Если она называет "
            "имя, значит, у сообщений в базе нет привязки к сессии и обе ленты "
            "слились в одну: это самая частая ошибка в задании дня. "
            "Проверить можно и после перезапуска — обе сессии останутся в списке "
