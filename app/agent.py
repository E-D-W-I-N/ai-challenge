COMPRESS_SYSTEM = (
    "Ты сворачиваешь начало разговора в сжатый пересказ. Не отвечай на сообщения "
    "и не обращайся к собеседнику: твой ответ целиком — пересказ, и он встанет "
    "в контекст вместо свёрнутых сообщений. Сохрани факты, имена, числа, решения "
    "и договорённости: дальше по ним будут задавать вопросы."
)
"""Системный промпт вызова на сжатие. Свой, а не `spec.system`: чат просили
отвечать, а здесь просят пересказывать, и чужая роль испортила бы пересказ."""


def build_compress_prompt(chunk: list["Turn"], previous: str | None = None) -> list[dict]:
    """Промпт вызова на сжатие: прошлая сводка плюс **новые** реплики.

    Сворачивание идёт инкрементально, а не пересказывает разговор с начала
    каждый раз: пересказ всей истории на каждом сворачивании съел бы ту самую
    экономию, ради которой сжатие заведено, — и рос бы вместе с разговором.
    """
    parts = []
    if previous:
        parts.append("Пересказ начала разговора, который надо продолжить:\n" + previous)
    lines = [
        f"{'Пользователь' if turn.role == 'user' else 'Ассистент'}: {turn.content}"
        for turn in chunk
    ]
    parts.append("Сообщения, которые надо добавить в пересказ:\n" + "\n".join(lines))
    return [
        {"role": "system", "content": COMPRESS_SYSTEM},
        {"role": "user", "content": "\n\n".join(parts)},
    ]


def summary_message(content: str, covered: int) -> dict:
    """Сводка так, как она встаёт в промпт: роль `user` и явная подпись,
    **не** `system`. Системный промпт по проекту живёт ровно в одном месте —
    `spec.system`, — и голый чат обязан уходить в модель без системной реплики.
    Подпись не украшение: без неё модель приняла бы пересказ за реплику
    пользователя и стала бы отвечать на него."""
    return {
        "role": "user",
        "content": (
            f"[пересказ начала разговора, свёрнуто сообщений: {covered}]\n"
            f"{content}\n"
            "[дальше — последние сообщения как есть]"
        ),
    }


# Условия «а вдруг это не новость» у блока задачи больше нет, и это разбор
# живого прогона, а не уборка.
#
# Блок заводился только от уведённого с умолчания этапа, заполненного поля
# или записи рабочей памяти, — то есть на планировании его в промпте
# не было **вовсе**. А планирование это умолчание: первый обмен всякого
# чата уходил в модель без единого слова о том, где задача находится, чего
# от неё ждут и что приступать к работе рано. Модель отвечала вслепую
# и дальше путалась в собственном статусе — ровно это и увидел живой прогон.
#
# Довод «умолчание само по себе не новость» был верен про человека и неверен
# про модель: человек видит полосу этапов в шапке, а модель не видит ничего,
# кроме промпта. Этап есть всегда — значит и блок есть всегда, при любом
# этапе, включая умолчание.
#
# Пустоту по-прежнему прячут оба слоя памяти и профиль (`memory_items`,
# `working_items`, `profile_items`), и это другой случай: у пустой памяти
# прятать нечего, пустая врезка сказала бы ровно ноль. У состояния задачи
# пустоты не бывает — этап назван всегда, и инструкция этапа при нём.
#
# Условие у блока всё-таки одно, и оно не про «новость», а про то, ведёт ли
# чат задачу вообще: «Рабочий процесс» выключен — задачи у чата нет, и блока
# нет вместе с ней. Это не «а вдруг умолчание», а прямой ответ человека
# переключателем, и молчит он ровно так же, как молчит пустая память:
# врезки нет, слот пуст, номера соседей не сдвинуты.


def task_shown(task: dict) -> dict:
    """Что этап **значит** прямо сейчас: зашитое картой, а поверх него —
    набранное человеком.

    Текст человека побеждает зашитый, и это единственное правило слияния.
    Карта (`TASK_STAGE_PLAN`) говорит, чем на этапе заняты и чего ждут, —
    и говорит за всякий чат, которому нечего сказать своего. Вписал человек
    «сейчас» руками — едет его: поле он для того и трогал, и затирать его
    умолчанием значило бы отменять правку, которую сам же и принял.

    Поля здесь только два, и оба — **сведения** о задаче. Правило этапа
    сюда не входит вовсе: оно распоряжение и едет системным сообщением
    (`task_rule`), а человеком не правится ни в каком виде.

    Незнакомый этап (карта у сервера другой версии была своя) не роняет
    ничего: зашитого у него нет, и в блок уедет только то, что вписал
    человек. Довод тот же, по которому незнакомая стратегия читается
    как `full`.
    """
    plan = TASK_STAGE_PLAN.get(task.get("stage"), {})
    return {
        name: (task.get(name) or plan.get(name, "")) for name in TASK_TEXT_FIELDS
    }


def task_rule(task: dict | None) -> str:
    """Правило этапа — то, что на нём **можно и нельзя**, одной строкой
    из карты (`TASK_STAGE_PLAN`). Пустая строка, если задачи у чата нет
    («Рабочий процесс» выключен) или этап незнакомый.

    Отдельной функцией, а не строкой внутри сборки промпта, потому что
    спрашивают её оттуда же, откуда и блок задачи, и ответ у неё один
    на оба места: системное сообщение промпта и строку под полосой этапов.
    """
    if not task:
        return ""
    return TASK_STAGE_PLAN.get(task.get("stage"), {}).get("rule", "")


def task_lines(task: dict) -> list[str]:
    """Состояние задачи строками «подпись поля: значение» — первыми строками
    блока задачи.

    Этап стоит первым и стоит **всегда**, пока блок есть: это то, где задача
    находится, и блок с целями, умолчавший про этап, заставил бы модель его
    угадывать. Уезжает он русской подписью и по одной карте с полосой этапов
    в шапке (`TASK_STAGE_LABELS`) — второй таблицей модель читала бы одно
    слово, а человек видел бы другое.

    Дальше — «сейчас» и «ожидается», и только **непустые**: пустое уехало
    бы строкой «ожидается: » и заняло бы место, не сказав ничего. Довод тот
    же, что у блока профиля.

    Правила этапа здесь нет: оно **распоряжение**, а не сведение, и едет
    системным сообщением (`task_rule`, `Agent.system_message`). Пока оно
    стояло здесь, последней строкой среди справок, маленькая модель читала
    его как одну из них — и на планировании выдавала готовый код вместо
    плана. Строка «этап: планирование» осталась: это факт о состоянии,
    а не правило.
    """
    lines = [f"{TASK_LABELS['stage']}: {TASK_STAGE_LABELS.get(task['stage'], task['stage'])}"]
    shown = task_shown(task)
    lines += [
        f"{TASK_LABELS[name]}: {shown[name]}" for name in TASK_TEXT_FIELDS if shown[name]
    ]
    return lines


def task_view(task: dict) -> dict:
    """Состояние задачи так, как его ждёт экран: само состояние, строки
    блока — те самые, что уедут в промпт, — правило этапа и список
    достижимых отсюда этапов.

    Строки отдаёт сервер, а не собирает клиент: под полосой этапов стоит
    ровно то, что **видит модель**, и собери их браузер сам — на экране
    и в промпте оказались бы два разных текста. Зашитые умолчания карты
    остались бы при этом второй таблицей на клиенте, а карта подписей
    у нас одна на всех.

    `moves` — тем же доводом и та же карта (`TASK_MOVES`), по которой
    переход разрешают или отбивают. Полоса этапов — пульт: текущий этап
    выделен, достижимые нажимаются, недостижимые приглушены и не нажимаются,
    то есть запрет виден **до** того, как его попытались нарушить. Считай
    клиент достижимость сам, и на экране стояла бы вторая карта переходов,
    расходящаяся с этой молча; отбивает запрещённое всё равно сервер —
    правило держится кодом, а не разметкой.
    """
    stage = task.get("stage", TASK_STAGE_DEFAULT)
    return {
        **task,
        "lines": task_lines(task),
        # Правило — отдельным полем, а не строкой блока: в промпте оно едет
        # системным сообщением, и подмешай его сюда — под полосой стояло бы
        # то, чего в блоке задачи нет. А показать его человеку обязательно:
        # это то, что велено модели, и увидеть его ему там же, где этап.
        "rule": task_rule(task),
        "moves": list(TASK_MOVES.get(stage, ())),
    }


def deny_note(stage: str, target: str) -> str:
    """Почему переход не состоялся — словами и русскими подписями этапов
    (`TASK_STAGE_LABELS`), теми же, какими они стоят на полосе.

    Этим текстом отвечает ручка переключения этапа. Полоса запрещённое
    и так приглушает, но правило держится **кодом**: запрос, пришедший
    мимо полосы, обязан получить отказ, и отказ обязан объяснять, куда
    отсюда можно.
    """
    label = TASK_STAGE_LABELS.get(target, target)
    if stage == TASK_STAGE_DEFAULT:
        reason = "план утверждает человек"
    else:
        allowed = TASK_MOVES.get(stage, ())
        if not allowed:
            reason = "задача уже закрыта"
        elif len(allowed) == 1:
            reason = f"сначала {TASK_STAGE_LABELS.get(allowed[0], allowed[0])}"
        else:
            reason = "можно только в " + " или ".join(
                TASK_STAGE_LABELS.get(name, name) for name in allowed
            )
    return f"переход в «{label}» отклонён: {reason}"


def working_lines(items: list[dict]) -> str:
    """Рабочая память строками «подпись типа: содержимое» — в том виде,
    в каком она уезжает в промпт разговора. Ни номеров, ни слова слоя здесь
    нет: в промпте разговора они ни к чему, а врезка обязана выглядеть так же,
    как выглядела выписка фактов, — читает её модель, которая отвечает
    собеседнику, а не правит список.

    Тип подписан по-русски и по одной карте с интерфейсом (`WORKING_LABELS`),
    ровно как у долговременной памяти: второй таблицей подписей модель читала
    бы одно слово, а пользователь видел бы другое."""
    return "\n".join(
        f"{WORKING_LABELS.get(item['kind'], item['kind'])}: {item['content']}"
        for item in items
    )


def working_message(items: list[dict], task: dict | None) -> dict:
    """Блок задачи так, как он встаёт в промпт: роль `user` и явная
    подпись, **не** `system`.

    `task` — состояние задачи или `None`, если чат её не ведёт
    («Рабочий процесс» выключен). Тогда блок собирается из одних записей
    рабочей памяти, каким он и был до Дня 13: слой человек наполняет руками,
    и от переключателя задачи он не зависит.

    Блок один на состояние задачи и на рабочую память, а не два соседних:
    этап, текущий шаг и записи — про одно и то же, оба слоя живут в чате
    и умирают с ним, и второй блок на ту же тему был бы ровно тем лишним
    разделением промпта, которого лекция велит избегать. Состояние идёт
    первым: сперва где задача, потом что про неё известно.

    Роль `user` с подписью, а не `system`, — довод тот же, что у сводки:
    системным сообщением едет распоряжение, а блок задачи это сведения,
    на которые модель опирается. Без подписи она приняла бы врезку за реплику
    пользователя и стала бы отвечать на неё.

    Подпись осталась прежней, хотя хранение сменилось дважды: врезка — это
    то, что видит модель, отвечающая собеседнику, и менять ей текст заодно
    со схемой базы значило бы поменять два ответа на один вопрос.

    А закрывающая скобка сменилась — и ровно потому, что врезка перестала
    быть врезкой стратегии. Раньше за ней шли только сообщения, теперь за ней
    может встать сводка начала разговора: «дальше — последние сообщения как
    есть» соврало бы там, где врезок в промпте три. Довод тот же, по которому
    нейтральна скобка у долговременной памяти.
    """
    lines = (task_lines(task) if task else []) + (
        [working_lines(items)] if items else []
    )
    return {
        "role": "user",
        "content": (
            "[факты о разговоре]\n" + "\n".join(lines) + "\n[конец фактов о разговоре]"
        ),
    }


def memory_lines(records: list[dict]) -> str:
    """Долговременная память строками «подпись типа: содержимое» — в том виде,
    в каком она уезжает в промпт. Тип подписан по-русски и по одной карте
    с интерфейсом (`MEMORY_LABELS`): второй таблицей подписей модель читала бы
    одно слово, а пользователь видел бы другое."""
    return "\n".join(
        f"{MEMORY_LABELS.get(record['kind'], record['kind'])}: {record['content']}"
        for record in records
    )


def memory_message(records: list[dict]) -> dict:
    """Долговременная память так, как она встаёт в промпт: роль `user` и явная
    подпись, **не** `system`. Довод тот же, что у сводки и выписки: системный
    промпт живёт ровно в одном месте — `spec.system`, — и голый чат обязан
    уходить в модель без системной реплики.

    Закрывающая скобка нейтральная — не «дальше сообщения как есть», как
    у сводки и фактов. Память стоит **первой**, и сразу за ней может встать
    врезка стратегии: пообещай мы здесь сообщения как есть, обещание соврало
    бы ровно в самом интересном случае — когда врезок в промпте две.
    """
    return {
        "role": "user",
        "content": (
            "[долговременная память]\n"
            f"{memory_lines(records)}\n"
            "[конец долговременной памяти]"
        ),
    }


def profile_block(values: dict) -> str:
    """Профиль строками «подпись поля: текст» под заголовком `[как отвечать]`.

    В блок попадают **только заполненные** поля и в том порядке, в каком они
    перечислены (`PROFILE_FIELDS`): пустое поле уехало бы строкой «формат: »
    и сказало бы модели ровно ничего, заняв место распоряжения.

    Подпись поля — по одной карте с интерфейсом (`PROFILE_LABELS`), ровно как
    у обоих слоёв памяти: второй таблицей подписей модель читала бы одно
    слово, а человек видел бы другое.
    """
    lines = [
        f"{PROFILE_LABELS.get(field, field)}: {values[field]}"
        for field in PROFILE_FIELDS
        if values.get(field)
    ]
    return "[как отвечать]\n" + "\n".join(lines)


def system_message(system: str, profile: dict, rule: str = "") -> dict | None:
    """Системное сообщение промпта — или `None`, если его нет вовсе.

    Здесь меняется правило, прожившее четыре дня: «системный промпт живёт
    ровно в одном месте — `spec.system`». Место у него по-прежнему одно,
    но **роль сообщения определяется источником**: системным сообщением едет
    то, что задал человек, — а профиль задал он, руками, во вкладке. Врезки
    памяти едут ролью `user` по тому же правилу с другой стороны: их
    содержимое человек тоже вписал, но встают они в промпт как сведения,
    на которые модель опирается, а не как распоряжение, которому следует.

    Профиль дописывается **в то же** сообщение, а не встаёт вторым системным:
    у чата ровно одно системное сообщение, и «кто ты» и «как отвечать»
    читаются как одно распоряжение.

    Третьим куском — правило этапа (`task_rule`), и по тому же правилу
    источника: «на каком этапе стоим и что на нём можно» это распоряжение,
    и задал его человек, переключив этап. Сведения о задаче — «сейчас»,
    «ожидается» и записи рабочей памяти — остались блоком задачи ролью
    `user`: они не велят, а сообщают. Пока правило ехало там же, среди
    них, маленькая модель читала его как справку и на планировании
    выдавала готовый код вместо плана.

    Порядок от общего к частному: кто ты, как отвечать, где задача.
    Пустой строкой правило не бывает — бывает только его отсутствие:
    «Рабочий процесс» выключен, и правила этапа в промпте нет вовсе,
    ровно как нет блока задачи.

    Ловушка здесь ровно одна, и она молчаливая: номера врезок берутся
    из длины уже собранного начала промпта, а системное сообщение
    заводится и у чата **без** `spec.system` — если непуст профиль или
    чат ведёт задачу. Правило «голый чат уходит без системной реплики»
    осталось прежним; голый теперь значит «ни системного промпта,
    ни профиля, ни задачи».
    """
    block = profile_block(profile) if profile else ""
    parts = [part for part in (system, block, rule) if part]
    if not parts:
        return None
    return {"role": "system", "content": "\n\n".join(parts)}


