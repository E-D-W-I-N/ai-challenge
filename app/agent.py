CUT_METRIC = {"summary": "summarized", "window": "dropped"}
"""Каким ключом обмен говорит, что начало истории не уехало дословно, — по
стратегии, которая его срезала. Ключ уходит в метрики обмена, и строка под
ответом называет по нему число: «сводка вместо N сообщений», «окно: отброшено
N сообщений». Слово на все случаи одно соврало бы про какой-нибудь из них:
сводка начало **заменила** — её видно в промпте запроса, — а окно его
**отбросило** совсем. У полной истории ключа нет вовсе: срезать нечего.
В суммы по чату ключ не идёт — их считает USAGE_FIELDS."""


_last_id = 0
_id_lock = threading.Lock()


def new_agent_id() -> str:
    """Следующий id по счётчику процесса. Для агента без хранилища — годится."""
    global _last_id
    with _id_lock:
        _last_id += 1
        return f"ag_{_last_id:05d}"


def reserve_ids(upto: int) -> None:
    """Сдвигает счётчик за самый большой id из базы.

    После перезапуска счётчик процесса начинается с нуля и выдал бы `ag_00001`
    заново — конструктор поднял бы под ним чужую историю. Настоящий арбитр —
    первичный ключ (`Store.claim_agent_id`), а это подсказка, экономящая попытку.
    """
    global _last_id
    with _id_lock:
        _last_id = max(_last_id, int(upto))


def copy_spec(spec: AgentSpec) -> AgentSpec:
    """Копия конфига, и вглубь тоже.

    `replace` копирует только верхний уровень: `stop`, `response_format`
    и `extra_body` остались бы одним объектом на всех, кого подняли из этого
    конфига, — правка у одного задела бы остальных.
    """
    return replace(
        spec,
        stop=list(spec.stop) if spec.stop else None,
        response_format=copy.deepcopy(spec.response_format),
        extra_body=copy.deepcopy(spec.extra_body or {}),
    )


class AgentBusyError(RuntimeError):
    """У агента уже идёт обмен. Второй параллельный запрос — ошибка, а не очередь:
    иначе две вкладки на одном агенте молча перемешали бы историю."""


@dataclass
class Turn:
    """Одна реплика в истории агента."""

    role: str
    content: str

    error: str | None = None
    """Заполнен, если ответ оборвался: реплика в истории есть, но она неполная."""

    reasoning: str = ""
    """Рассуждение модели: в `content` не входит и обратно в модель не уходит."""

    metrics: dict | None = None
    """Метрики этого ответа: по ним рисуются плитки внизу справа."""

    at: float = field(default_factory=time.time)
    """Время реплики: с ним она уезжает в базу и возвращается оттуда."""

    def as_message(self) -> dict:
        """Реплика в том виде, в каком она уходит в модель: в контекст
        возвращается ответ, а не путь к нему."""
        return {"role": self.role, "content": self.content}


@dataclass
class Exchange:
    """Снятая с истории пара «вопрос — ответ» — то, что можно вернуть назад."""

    question: str
    turns: list[Turn]
    depth: int
    """Длина истории сразу после снятия: по ней видно, занял ли место кто-то другой."""


class Agent:
    """Один агент: конфиг + история + один метод обмена. Инстанцируется дёшево
    и много: ни сети, ни потоков, ни подпроцессов в конструкторе."""

    def __init__(
        self,
        spec: AgentSpec,
        *,
        agent_id: str | None = None,
        context_length: int | None = None,
        store: Store | None = None,
    ) -> None:
        # Свежий id занимает база, а не процесс: сервер и консоль ходят в один
        # файл, и локальный счётчик выдал бы обоим один номер (см. app/store.py).
        # Без хранилища агент живёт только в памяти — там и счётчика хватает.
        claimed = False
        if agent_id is not None:
            self.id = agent_id
        elif store is not None:
            self.id = store.claim_agent_id()
            claimed = True
        else:
            self.id = new_agent_id()

        try:
            self._setup(spec, agent_id, context_length, store)
        except BaseException:
            # Строку под этот id мы уже заняли. Не достроились — убираем
            # за собой, иначе в списке слева повис бы чат без объекта.
            if claimed and store is not None:
                with contextlib.suppress(Exception):
                    store.delete_session(self.id)
            raise

    def _setup(
        self,
        spec: AgentSpec,
        agent_id: str | None,
        context_length: int | None,
        store: Store | None,
    ) -> None:
        """Всё, что собирается после того, как id уже занят.

        Вынесено из `__init__` ради уборки: конструктор ловит любое исключение
        отсюда и освобождает занятую строку.
        """
        # Свой экземпляр конфига каждому агенту: один и тот же spec может
        # поднять сотню, и правка у одного не должна задеть остальных.
        self.spec = copy_spec(spec)
        self.created_at = time.time()
        self.last_used_at = self.created_at
        self.context_length = context_length

        self.history: list[Turn] = []
        """Только то, что наговорили в диалоге. Системный промпт — в spec.

        Сжатие её **не трогает**: она полная всегда, сколько бы сворачиваний
        ни прошло. Иначе сломалась бы перегенерация — `take_last_exchange`
        ждёт хвост `["user", "assistant"]`, а `restore` сверяет длину.
        """

        self.summaries: list[dict] = []
        """Сводки начала разговора, по порядку сворачивания: `{upto, content,
        metrics, at}`. Последняя — действующая, `upto` у неё говорит, сколько
        первых реплик истории она собой заменяет. Список, а не одна сводка:
        у каждого сворачивания свои метрики, и без них счёт стоимости сжатия
        был бы неполным."""

        self.working: list[dict] = []
        """Рабочая память чата: записи о состоянии задачи, `{seq, kind,
        content, at}` каждая, в порядке номеров.

        Просто список, без единого числа рядом. Числа там были про **вызов**
        — докуда он дочитал историю и во что обошёлся, — а вызова больше нет:
        записи заводит и правит только человек, руками, через вкладку.
        Автоматическая запись жила один день и на живом прогоне оказалась
        непредсказуемой, а чинить её вслепую, без ключа, нельзя.

        Отсюда и всё остальное, чего здесь нет: ни курсора прочитанного, ни
        зажима окна по нему, ни автора у записи — писать в этот слой больше
        некому, кроме собеседника.
        """

        self.task: dict = blank_task()
        """Состояние этой задачи: этап, текущий шаг и ожидаемое действие.

        Держится в памяти, а не спрашивается у базы на каждый показ: полоса
        этапов уезжает клиенту с самим чатом, и отдельный запрос под неё
        превратил бы один поход на сервер в поток.

        Переключает его **человек**, нажимая на полосу этапов: ни одного
        метода, выводящего этап из разговора, у агента нет — довод тот же,
        по которому он не пишет ни в один слой памяти.
        """

        self.task_log: list[dict] = []
        """Журнал этапа: `{seq, stage_from, stage_to, who, ok, at}` на каждый
        переход и на каждую отклонённую попытку.

        Состояние — это где задача **сейчас**, журнал — как она сюда пришла.
        Держится в памяти рядом со сводками и по тому же доводу: он уезжает
        клиенту вместе с чатом, и ходить за ним в базу на каждую отрисовку
        полосы значило бы превратить один поход в поток.
        """

        self._working_seq = 0
        """Последний выданный номер записи — на случай агента **без
        хранилища**. С хранилищем номера выдаёт база (AUTOINCREMENT), и здесь
        просто запоминается наибольший выданный: правило у обоих одно —
        только вперёд, номер удалённой записи заново не выдаётся."""

        self.branch: dict | None = None
        """Происхождение чата: `{parent_id, forked_at}` — или `None`, если чат
        заведён сам по себе.

        Не в `spec`: конфиг это «чем один чат отличается от другого», а от
        кого ты отделился — не настройка, и менять её из панели нельзя.
        Имени родителя здесь нет — только id: имя меняют из списка слева,
        и копия рядом с родством разошлась бы с ним на первом же
        переименовании.
        """

        self._lock = asyncio.Lock()
        self._cancel = asyncio.Event()
        self._reserved = False

        self.store = store
        """Хранилище сессии. None — агент живёт только в памяти процесса.

        Обнуляется при выгрузке из реестра: с этого момента объект больше
        не владелец сессии и писать в неё ему нельзя (см. `detach`).
        """

        if store is not None:
            # Восстановление здесь, а не отдельным вызовом: забыть его позвать
            # должно быть невозможно.
            saved = store.load_session(self.id) if agent_id else None
            if saved is not None:
                self.spec = spec_from_config(saved["config"], fallback=self.spec)
                self.created_at = saved["created_at"]
                self.last_used_at = saved["updated_at"]
                if saved.get("context_length") is not None and context_length is None:
                    # Метрикам нужен context_fill_pct, а каталог моделей —
                    # сетевой запрос: восстановление не должно его ждать.
                    self.context_length = saved["context_length"]
                self.history = [
                    Turn(
                        role=m["role"],
                        content=m["content"],
                        error=m["error"],
                        metrics=m["metrics"],
                        at=m["at"],
                    )
                    for m in store.load_messages(self.id)
                ]
                # Сводки лежат отдельно от истории и поднимаются отдельно:
                # перезапись истории их не трогает, и после перезапуска
                # свёрнутое начало разговора остаётся свёрнутым.
                self.summaries = store.load_summaries(self.id)
                # Рабочая память — тем же порядком и по тому же доводу:
                # записи переживают перезапуск, и номера у них те же.
                self.working = store.list_working(self.id)
                self._working_seq = max(
                    (item["seq"] for item in self.working), default=0
                )
                # И состояние задачи — тем же порядком: пауза и продолжение
                # разговора в том и состоят, что этап, шаг и ожидаемое
                # действие поднимаются из файла такими же, какими их
                # оставили. Строки может не быть вовсе — тогда умолчание.
                self.task = store.load_task(self.id)
                # И журнал его переходов: летопись задачи переживает
                # перезапуск ровно как сама задача — иначе вернувшийся
                # в разговор увидел бы этап без истории того, как он
                # сюда попал.
                self.task_log = store.list_task_log(self.id)
                # И происхождение: ветка остаётся веткой и после перезапуска,
                # и после вытеснения из памяти — пометка в списке и в панели
                # берётся отсюда.
                self.branch = store.load_branch(self.id)
            self.save_config()

    # --- состояние -----------------------------------------------------------

    @property
    def busy(self) -> bool:
        return self._lock.locked() or self._reserved

    def reserve(self) -> None:
        """Занимает агента синхронно, до первого await.

        Иначе между проверкой «занят?» и первым `await` в генераторе пролезает
        второй запрос и получает 200 с ошибкой внутри потока вместо честного
        409. Освобождает `release`, и обязательно в finally.
        """
        if self.busy:
            raise AgentBusyError(f"агент {self.id} уже занят: дождитесь текущего ответа")
        self._reserved = True

    def release(self) -> None:
        self._reserved = False

    def cancel(self) -> None:
        """Просит прекратить генерацию. Задачу извне не отменяет: агент сам
        выходит на ближайшем чанке, дописывает частичный ответ и закрывает
        поток штатным `done`."""
        self._cancel.set()

    # --- история -------------------------------------------------------------

    def summary_cover(self, spec: AgentSpec | None = None) -> int:
        """Сколько первых реплик истории заменено сводкой — 0, если сводки нет
        или сжатие выключено.

        Больше длины истории не бывает: перегенерация снимает пару **с конца**,
        и сводка не вправе покрывать то, чего в истории уже нет. Без этого
        зажима короткий чат после перегенерации дал бы промпт, в котором
        свёрнутого больше, чем было.
        """
        spec = spec if spec is not None else self.spec
        if spec.keep_last is None or not self.summaries:
            return 0
        upto = self.summaries[-1].get("upto")
        if not isinstance(upto, int) or upto <= 0:
            return 0
        return min(upto, len(self.history))

    def working_items(self, spec: AgentSpec | None = None) -> list[dict]:
        """Что из рабочей памяти уедет врезкой в этот промпт — записи или
        пустой список.

        Пусто — значит врезки нет вовсе, а не пустая: чат на свежей базе
        иначе получал бы в промпт пустую врезку, и всякая последовательность
        ролей, на которую смотрит любая проверка, сдвинулась бы на сообщение.
        Довод и форма те же, что у `memory_items`.
        """
        return list(self.working)

    def task_items(self, task=None) -> dict:
        """Состояние задачи, которое уедет в этот промпт, — всегда полный
        словарь: этап у задачи есть всегда.

        Пустым словарём ответить нельзя: этап уезжает первой строкой блока
        задачи, а блок едет при каждом обмене. «Состояние не задано» у чата
        не бывает вовсе — бывают только незаполненные текстовые поля, и их
        отбрасывает `task_lines`.

        `task` — уже прочитанное состояние: обмен читает его **один раз**
        и передаёт сюда и в слоты, ровно как память и профиль.
        """
        if task is not None:
            return dict(task)
        return dict(self.task)

    def set_task(self, values: dict) -> dict:
        """Правит текстовые поля состояния — названные, остальные не трогает.

        Этапа здесь нет и быть не может: у каждого перехода ровно один
        механизм, и ни один из них не проходит тут. «Сейчас» и «ожидается» —
        тексты, а не переходы, и правит их человек руками; журнала правка
        поля не касается вовсе.
        """
        if self.store is not None:
            self.task = self.store.save_task(self.id, values)
        else:
            self.task.update(
                {name: values[name] for name in self.task if name in values}
            )
        return dict(self.task)

    def _log_move(self, stage_from: str, stage_to: str, who: str, ok: bool) -> None:
        """Дописывает строку журнала этапа — и в базу, и в список в памяти.

        Через один метод, а не в хранилище напрямую: список в памяти обязан
        совпадать с базой — он уезжает клиенту вместе с чатом, и разъехавшись,
        экран и файл рассказали бы разные истории.

        Пишутся и **отклонённые** попытки (`ok=False`): журнал обязан
        показывать не только то, что переходы случаются, но и то, что
        запрещённые не случаются, — иначе поверить автомату можно только
        на слово.
        """
        if self.store is not None:
            self.task_log.append(
                self.store.add_task_move(
                    self.id,
                    stage_from=stage_from,
                    stage_to=stage_to,
                    who=who,
                    ok=ok,
                )
            )
            return
        self.task_log.append(
            {
                "seq": len(self.task_log) + 1,
                "stage_from": stage_from,
                "stage_to": stage_to,
                "who": who,
                "ok": ok,
                "at": time.time(),
            }
        )

    def move_stage(self, target: str, who: str = "human") -> str:
        """Уводит задачу на `target`, если карта переходов это разрешает.
        Отдаёт исход — `moved`, `same`, `denied` или `unknown`.

        Единственная дверь всех переходов: карта стоит здесь, в одном
        месте, и второй её копии нет нигде — ни на клиенте, ни в ручке.
        Две копии разошлись бы молча, и прыжок, отбитый в одном месте,
        прошёл бы в другом.

        Исходов четыре, потому что различать их обязаны и журнал, и тот,
        кто попросил:

        * `same` — попросили тот этап, на котором и стоим. Это **не** ошибка
          и не переход: ничего не записывается, журнал молчит. Иначе он
          зарос бы строками ни о чём;
        * `moved` — карта разрешает, этап переехал, журнал получил строку;
        * `denied` — карта запрещает, состояние прежнее, но строка в журнале
          есть: отклонённая попытка это улика того, что автомат работает;
        * `unknown` — этапа с таким именем нет вовсе. В журнал не идёт:
          переходом это не было, и рисовать в летописи стрелку в никуда
          значило бы врать.
        """
        stage = self.task.get("stage", TASK_STAGE_DEFAULT)
        if not isinstance(target, str) or target not in TASK_STAGES:
            return "unknown"
        if target == stage:
            return "same"
        if not task_move_allowed(stage, target):
            self._log_move(stage, target, who, ok=False)
            return "denied"
        if self.store is not None:
            self.task = self.store.save_task(self.id, {"stage": target})
        else:
            self.task["stage"] = target
        self._log_move(stage, target, who, ok=True)
        return "moved"

    def context_cut(self, spec: AgentSpec | None = None) -> tuple[int, dict | None]:
        """Что стратегия делает с началом истории: сколько первых реплик не
        уехало в модель дословно и что встало вместо них (`None` — ничего).

        Одна точка разбора по `spec.strategy`, и обе половины ответа берутся
        из неё разом: разъедься число с врезкой — промпт заявил бы сводку на
        десять реплик, а срезал бы восемь, и узнать об этом было бы неоткуда.

        * `full` — не срезается ничего, уезжает вся история, как в Дне 8;
        * `window` — уезжают последние `keep_last` реплик, остальные
          отброшены **вовсе**, и вместо них не встаёт ничего: сколько их
          было, сказано под ответом, а не в промпте;
        * `summary` — срезано ровно то, что покрыла сводка, и она же встаёт
          вместо срезанного.

        Врезки рабочей и долговременной памяти здесь больше нет ни одной:
        обе едут при **любой** стратегии и ни одну из них не отменяют —
        собирает их `build_prompt`. Стратегия теперь отвечает ровно на один
        вопрос: сколько реплик уедет дословно.

        Незнакомое значение читается как `full`. Ручки чужого не пропустят
        (`_choice_field`), но конфиг мог записать сервер другой версии, и
        падать на нём — значит потерять диалог. Резать по значению, смысла
        которого мы не знаем, нельзя: обрезка бывает только выбранная.
        """
        spec = spec if spec is not None else self.spec
        if spec.strategy == "window":
            # Пустое поле — отбрасывать нечем: идиом тот же, что у
            # сэмплирования, None это «не делать», а не «делать с нулём».
            if spec.keep_last is None:
                return 0, None
            # Окно режет ровно столько, сколько просили. Зажима по «докуда
            # дочитала память» здесь больше нет: он стерёг реплику, которую
            # окно выбросило бы раньше, чем её прочитало ведение, — а ведения
            # не стало, и записи в рабочей памяти теперь не зависят от того,
            # докуда дошёл разговор. Их вписал человек, и в промпте они стоят
            # врезкой независимо от того, что окно отбросило.
            return max(0, len(self.history) - spec.keep_last), None
        if spec.strategy == "summary":
            covered = self.summary_cover(spec)
            if not covered:
                return 0, None
            return covered, summary_message(self.summaries[-1]["content"], covered)
        return 0, None

    def memory_items(self, spec: AgentSpec | None = None, memory=None) -> list[dict]:
        """Что из долговременной памяти уедет в этот промпт — записи или пустой
        список.

        Пусто здесь значит одно и то же в двух случаях: память пуста и
        хранилища у агента нет. Условие поэтому одно, а не два: **пустая
        память обязана быть неотличима от отсутствующей** — иначе чат
        на свежей базе получал бы в промпт пустую врезку, и всякая
        последовательность ролей, на которую смотрит любая проверка,
        сдвинулась бы на сообщение. Третьим случаем здесь был выключатель
        чата; его не стало, а условие как было одним, так и осталось.

        `memory` — уже прочитанный список: обмен читает память **один раз**
        и передаёт сюда и в слоты одно и то же. Прочитай их по отдельности —
        запись, добавленная соседней вкладкой между сборкой промпта и кадром
        `start`, развела бы промпт с номером врезки в нём.
        """
        spec = spec if spec is not None else self.spec
        if memory is not None:
            return list(memory)
        if self.store is None:
            return []
        return self.store.list_memory()

    def profile_items(self, profile=None) -> dict:
        """Что из профиля уедет в промпт — заполненные поля или пустой словарь.

        Условие одно на два случая, как у `memory_items`: профиль пуст или
        хранилища у агента нет. **Пустой профиль обязан быть неотличим
        от отсутствующего** — и здесь это строже, чем у памяти: профиль
        заводит собой **системное** сообщение, и пустой блок сдвинул бы
        не только себя, а номера всех врезок разом.

        `profile` — уже прочитанный словарь: обмен читает профиль один раз
        и передаёт сюда и в сборку промпта, ровно как память.
        """
        if profile is not None:
            return dict(profile)
        if self.store is None:
            return {}
        return self.store.load_profile()

    def prompt_head(
        self, spec: AgentSpec | None = None, memory=None, profile=None, task=None
    ) -> tuple[list[dict], dict[str, int | None], int]:
        """Начало промпта разом: сообщения **до** истории, номер каждой врезки
        в них и срез, с которого история уезжает дальше.

        Одно место на два вопроса, которые раньше отвечались порознь: «что
        стоит перед историей» решала сборка промпта, а «каким это по счёту» —
        три отдельных метода, и каждый заново складывал сумму предыдущих
        врезок. Сумма, переписанная четырежды, расходится не громко, а молча:
        врезок в промпте станет четыре, поправят три места из четырёх — и
        просмотр промпта подпишет памятью чужое сообщение.

        Номер здесь не считается вовсе: он **берётся** из длины уже собранного
        начала. Разойтись с порядком сборки ему поэтому негде — порядок и есть
        единственный источник обоих ответов.

        Порядок от общего к частному: системное сообщение (системный промпт
        чата, профиль и правило этапа — всё, что задал человек, и всё,
        чему модель следует), долговременная память (что знали до чата),
        рабочая память и состояние задачи (что знаем про эту задачу), врезка
        стратегии (чем свёрнут сам чат). Ноль — законное значение любого
        номера: у чата без системного промпта первая же врезка стоит нулевым
        сообщением, и «врезки нет» — это только `None`.
        """
        spec = spec if spec is not None else self.spec

        messages: list[dict] = []
        slots: dict[str, int | None] = {name: None for name in PROMPT_SLOTS}
        # Состояние задачи читается до сборки: правило этапа едет системным
        # сообщением, а сведения о задаче — блоком ниже, и оба берутся
        # из одного прочитанного состояния. «Рабочий процесс» выключен —
        # задачи у чата нет, и нет ни того ни другого.
        state = self.task_items(task) if spec.workflow == "on" else None
        # Системное сообщение — то, что задал человек: системный промпт чата,
        # профиль и правило этапа. Своего номера у него нет и не нужно:
        # оно всегда первое, и клиент подписывает его по позиции. А вот
        # на номера **остальных** врезок оно влияет прямо, и потому собрано
        # здесь же, где они берутся, — одним `system_message`.
        head = system_message(
            spec.system, self.profile_items(profile), task_rule(state)
        )
        if head is not None:
            messages.append(head)

        records = self.memory_items(spec, memory)
        if records:
            slots["memory_at"] = len(messages)
            messages.append(memory_message(records))

        # Блок задачи — один на состояние и на записи о ней: и то и другое
        # про текущую задачу, оба живут в чате и умирают с ним. Состояние
        # едет при **любом** этапе, включая умолчание: модель не видит ни
        # полосы этапов, ни панели — только промпт, и «где задача» для неё
        # самая нужная новость. Едут им **сведения**: где задача и что про
        # неё известно. Что на этапе можно и нельзя — распоряжение, и оно
        # уже уехало системным сообщением выше.
        #
        # Но едет оно только у чата, который задачу **ведёт**: «Рабочий
        # процесс» выключен — и блока нет вовсе, а чат идёт обычным
        # разговором, каким был до Дня 13. Записи рабочей памяти от
        # переключателя не зависят: их вписал человек, и блок из одних
        # записей встаёт при любом его положении. Пусто и то и другое —
        # врезки нет, и слот у неё пуст: пустой блок сдвинул бы номера
        # соседей, не сказав ни слова.
        items = self.working_items(spec)
        if items or state is not None:
            slots["working_at"] = len(messages)
            messages.append(working_message(items, state))

        cut, insert = self.context_cut(spec)
        if insert is not None:
            slots["summary_at"] = len(messages)
            messages.append(insert)

        return messages, slots, cut

    def build_prompt(
        self, user_text: str, *, spec: AgentSpec | None = None, memory=None,
        profile=None, task=None,
    ) -> list[dict]:
        """Системный промпт + долговременная память + рабочая память + начало
        истории по стратегии + хвост + вопрос.

        Единственное место, где решается состав промпта. Обрезка бывает только
        та, которую выбрали переключателем, и всегда названа: `full` и
        `summary` не теряют ни реплики (у сводки свёрнутое плюс хвост равно
        длине истории), `window` отбрасывает начало по прямой просьбе, и
        сколько именно — написано под ответом (`dropped` в метриках обмена).

        Врезок памяти две, и ни одна из них не заменяет собой начало
        разговора: они встают при **любой** стратегии и ни одну не отменяют.
        Собирает их `prompt_head` — там же, где считаются их номера.

        Конфиг читается каждый раз, поэтому правка в панели видна со следующего
        сообщения; `spec` передаёт обмен — он собирает промпт и тело запроса
        из одного слепка, и память читает один раз на обмен.
        """
        messages, _, cut = self.prompt_head(spec, memory, profile, task)
        messages.extend(turn.as_message() for turn in self.history[cut:])
        messages.append({"role": "user", "content": user_text})
        return messages

    def prompt_slots(
        self, spec: AgentSpec | None = None, memory=None, profile=None, task=None
    ) -> dict[str, int | None]:
        """Номера всех врезок промпта разом: `memory_at`, `working_at`,
        `summary_at`. `None` у любого — врезки в промпте нет вовсе.

        Отдаёт их **одним** ответом, а не тремя методами по одному, и это
        не удобство вызывающего: три ответа считались бы по трём копиям одной
        формулы, и разошлись бы они молча. Уезжают они тоже разом — одним
        кадром `start`, — и спрашивать их порознь было бы неоткуда.
        """
        return self.prompt_head(spec, memory, profile, task)[1]

    def compress_plan(self, spec: AgentSpec) -> tuple[int, int] | None:
        """Что предстоит свернуть этим обменом: `(свёрнуто, новая граница)` —
        или `None`, если порог не набран и сворачивания не будет.

        Отдельно от самого сворачивания, потому что спросить надо **до** него:
        вызов на сжатие идёт к модели и длится неизвестно сколько, а клиент
        всё это время смотрит в пустую карточку. Событие `compressing` шлётся
        по этому же ответу — значит, «сейчас свернём» и «свернули» решаются
        одним кодом и разойтись не могут: обещание строки состояния держится
        не совпадением двух условий, а тем, что условие одно.
        """
        # Стратегия спрашивается здесь же, где порог: «сворачивать ли» обязано
        # решаться одним кодом. Второе условие рядом — у события `compressing`
        # или у сборки промпта — однажды разошлось бы с этим молча.
        if spec.strategy != "summary":
            return None
        keep, every = spec.keep_last, spec.compress_every
        if keep is None or every is None or keep < 0 or every <= 0:
            return None
        covered = self.summary_cover(spec)
        # Граница не рвёт пару: история идёт парами «вопрос — ответ», обе
        # реплики пишутся разом, и свёрнутый вопрос без своего ответа сделал бы
        # хвост бессмысленным. Округляем вниз до чётного.
        border = ((len(self.history) - keep) // 2) * 2
        if border - covered < every:
            return None
        return covered, border

    async def compress(self, spec: AgentSpec, context_length: int | None = None) -> None:
        """Сворачивает начало истории в сводку, если несвёрнутого накопилось
        больше порога. Зовётся из `ask` **до** сборки промпта: обмен, который
        запустил сворачивание, уже сам едет сжатым, и экономия видна во
        входных токенах этого же ответа, а не следующего.

        Сама история не трогается — сводка лишь заменяет её начало при сборке
        промпта. Не удалось сжатие (ошибка, пустой ответ) — история не режется:
        обмен просто уедет полным.

        Событие о том, что сворачивание идёт, шлёт `ask` — до вызова
        и по ответу `compress_plan`, того же кода, по которому вызов
        и случается: обещание строки состояния держится не совпадением
        двух условий, а тем, что условие одно.
        """
        plan = self.compress_plan(spec)
        if plan is None:
            return
        covered, border = plan
        chunk = self.history[covered:border]
        if not chunk:
            return

        # Формат ответа и стоп-строки на время сжатия сняты: чат с
        # {"type": "json_object"} вернул бы вместо пересказа объект, а
        # стоп-строка оборвала бы пересказ на середине. Модель и параметры
        # сэмплирования — те же: вторая модель развалила бы счёт на две цены.
        folding = replace(spec, response_format=None, stop=None)
        prompt = build_compress_prompt(chunk, self.summaries[-1]["content"] if covered else None)

        content = ""
        metrics: dict | None = None
        try:
            stream = stream_completion(folding, prompt_override=prompt, context_length=context_length)
            async with contextlib.aclosing(stream):
                async for event in stream:
                    if event["type"] == "done":
                        content = event["text"]
                        metrics = event["metrics"]
                    elif event["type"] == "error":
                        return
        except Exception:  # noqa: BLE001 — падает сжатие, обмен живёт
            # Сжатие — не сам обмен: не вышло свернуть, значит история уедет
            # целиком. Про отсутствие ключа расскажет сам обмен, следом.
            return
        if not content.strip():
            return

        self.summaries.append(
            {"upto": border, "content": content, "metrics": metrics, "at": time.time()}
        )
        if self.store is not None:
            self.store.save_summaries(self.id, self.summaries)

    # --- рабочая память: записи человека --------------------------------------
    #
    # Пишет сюда **только человек**, через ручки под чатом. Служебного
    # вызова, который вёл бы этот список сам, больше нет ни одного: он жил
    # один день и на живом прогоне записывал через раз, а чинить его вслепую,
    # без ключа, нельзя. Заодно исчезло и поле автора: когда пишущая сторона
    # одна, «кто записал» не различает ничего.
    #
    # Записи ходят через эти три метода, а не в хранилище напрямую: список
    # в памяти процесса обязан совпадать с базой — из него собирается врезка
    # в промпт и он же уезжает ветке.
    #
    # Долговременного слоя здесь нет ни одного метода, и это **устройство**,
    # а не обещание: пути записать туда у агента не осталось вовсе. Туда
    # кладёт только человек, явно выбирая, что переживёт задачу.

    def _working_find(self, seq) -> dict | None:
        """Запись по номеру — или `None`, если такой в этом чате нет."""
        if not isinstance(seq, int):
            return None
        return next((item for item in self.working if item["seq"] == seq), None)

    def _working_add(self, kind: str, content: str, at=None) -> dict:
        """Заводит запись и отдаёт её — вместе с номером.

        Номер выдаёт база: у `working_memory.seq` стоит AUTOINCREMENT, и
        номер удалённой записи не достаётся следующей. Без хранилища счёт
        ведёт сам агент — тем же правилом и только вперёд: агент без базы
        живёт в памяти процесса, но список записей у него такой же.
        """
        if self.store is not None:
            record = self.store.add_working(self.id, kind, content, at)
        else:
            self._working_seq += 1
            record = {
                "seq": self._working_seq,
                "kind": kind,
                "content": content,
                "at": time.time() if at is None else at,
            }
        self._working_seq = max(self._working_seq, record["seq"])
        self.working.append(record)
        return record

    def _working_write(self, record: dict, kind: str, content: str) -> dict:
        """Переписывает запись на месте. Номер не трогается: он и есть её
        идентичность — на него ссылается и служебный вызов, и вторая вкладка,
        и правка, сдвинувшая бы номера соседей, удалила бы у них не ту запись.
        """
        stamp = time.time()
        if self.store is not None:
            saved = self.store.update_working(
                self.id, record["seq"], kind=kind, content=content, at=stamp
            )
            if saved is not None:
                record.update(saved)
                return record
        record.update(kind=kind, content=content, at=stamp)
        return record

    def _working_drop(self, record: dict) -> None:
        """Убирает запись. Номер после этого не достаётся никому."""
        if self.store is not None:
            self.store.delete_working(self.id, record["seq"])
        self.working.remove(record)

    def add_working_record(self, kind: str, content: str) -> dict:
        """Запись, сделанная человеком, — других здесь и не бывает."""
        return self._working_add(kind, content)

    def edit_working_record(self, seq: int, *, kind=None, content=None) -> dict | None:
        """Правка руками: меняет названное, остальное оставляет. `None` —
        записи с таким номером в этом чате нет."""
        record = self._working_find(seq)
        if record is None:
            return None
        return self._working_write(
            record,
            kind or record["kind"],
            record["content"] if content is None else content,
        )

    def drop_working_record(self, seq: int) -> bool:
        """Удаление руками. False — записи с таким номером в этом чате
        не было."""
        record = self._working_find(seq)
        if record is None:
            return False
        self._working_drop(record)
        return True

    def remember(
        self,
        role: str,
        content: str,
        error: str | None = None,
        *,
        reasoning: str = "",
        metrics: dict | None = None,
        persist: bool = True,
    ) -> None:
        self.history.append(
            Turn(role=role, content=content, error=error, reasoning=reasoning, metrics=metrics)
        )
        if persist:
            self.persist()

    def carry_off(self, at: int) -> dict:
        """Что унесёт ветка, отделённая по `at`-е сообщение включительно:
        копия начала истории плюс те врезки, чья граница не дальше точки
        ветвления.

        Копия глубокая: и `Turn`, и его метрики у ветки свои. Общий объект
        сделал бы два чата одним в той части, которую они делят, — а ветка
        обязана быть независимой не только в базе, но и в памяти процесса.

        Родителя метод **только читает**. Писать в чужую сессию не вправе
        никто (см. `detach`), а `save_history` начинается с `DELETE` — одна
        случайная запись отсюда стёрла бы родителю разговор.

        **Сводка едет не всегда.** Ветка, унёсшая половину разговора,
        не вправе унести сводку про весь: сводка **заменяет собой** начало
        истории, и заменять им можно ровно то начало, которое в ветке есть.
        Обрезать её по смыслу нельзя — это связный текст, — поэтому правило
        по границе: едет та, что покрывает **только** унесённое (`upto <=
        at`). Сводки инкрементальны, и префикс их списка сам по себе готовая
        сводка своего начала.

        **А рабочая память едет вся.** Раньше и она ехала по границе — её
        вёл служебный вызов, читавший историю, и записи были про
        прочитанное. Теперь их вписывает человек: это его слова о задаче,
        а не пересказ чьих-то реплик, и ни одной реплики они собой
        не заменяют — они добавляются. Ветка продолжает ту же задачу, значит
        уносит её цели и ограничения целиком.

        Метрики у копий остаются: ветка уносит и метрики унесённых ответов,
        и итог по чату честно говорит, во что обошёлся тот разговор, который
        в ней лежит. Сняв числа у сводки, мы сделали бы её в ветке
        бесплатной, а унесённые ответы — нет.
        """
        return {
            "history": [
                replace(turn, metrics=copy.deepcopy(turn.metrics))
                for turn in self.history[:at]
            ],
            "summaries": [
                copy.deepcopy(item)
                for item in self.summaries
                if isinstance(item.get("upto"), int) and item["upto"] <= at
            ],
            "working": [copy.deepcopy(item) for item in self.working],
            # **И состояние задачи едет целиком** — по тому же правилу, что
            # рабочая память, и по тому же доводу: этап не заменяет собой ни
            # одной реплики, он про задачу, а задача у ветки та же. Границы
            # по `at` у него поэтому нет: ветвиться посреди проверки и
            # оказаться снова на планировании значило бы потерять то, что
            # ветка как раз и продолжает.
            "task": dict(self.task),
        }

    def take_branch(self, carried: dict, *, parent_id: str, forked_at: int) -> None:
        """Принимает унесённое ветвлением и записывает происхождение.

        Всё одной транзакцией, как пара «вопрос — ответ»: ветка появляется
        либо со всем унесённым, либо никакой. Умри процесс посередине —
        в базе остался бы чат с историей, но без родства, и пометки ветки
        у него не было бы никогда.
        """
        self.history = carried["history"]
        self.summaries = carried["summaries"]
        self.branch = {"parent_id": parent_id, "forked_at": forked_at}

        # Записи памяти заводятся заново, а не переносятся с номерами: номер
        # принадлежит одному чату, и две записи под одним номером в разных
        # разговорах — ровно та путаница, из-за которой номера и стали
        # сквозными. Содержимое, тип и время у копий прежние.
        self.working = []
        self.task = dict(carried["task"])
        # А журнал этапа ветка **не уносит**, и это не пропуск: журнал —
        # летопись того, как задача пришла в это состояние, и переходы
        # в ней случились в разговоре родителя. Ветка продолжает ту же
        # задачу с того же этапа, но её собственная летопись начинается
        # с ветвления. Довод тот же, по которому не копируется
        # долговременная память: ветке достаётся состояние, а не чужое
        # прошлое.
        self.task_log = []
        if self.store is None:
            for item in carried["working"]:
                self._working_add(item["kind"], item["content"], item["at"])
            return
        with self.store.tx():
            self.store.save_branch(self.id, parent_id=parent_id, forked_at=forked_at)
            self.store.save_summaries(self.id, self.summaries)
            self.store.save_task(self.id, self.task)
            for item in carried["working"]:
                self._working_add(item["kind"], item["content"], item["at"])
            self.persist()

    def detach(self) -> None:
        """Снимает с объекта право писать в сессию — зовётся при выгрузке.

        Сессией владеет тот объект, что лежит в реестре. Иначе придержанная
        ссылка пережила бы вытеснение, обращение по id подняло бы из базы
        **второй** объект той же сессии, и запись первого затёрла бы реплики
        второго. Терять нечего: и история, и конфиг уже записаны.
        """
        self.store = None

    def persist(self) -> None:
        """Пишет историю в хранилище. Без хранилища — тихо ничего не делает."""
        if self.store is not None:
            self.store.save_history(self.id, self.history)

    def save_config(self) -> None:
        """Пишет конфиг сессии целиком, одним JSON-полем.

        Конфиг едет как `asdict(spec)`, поэтому новое поле сохраняется само,
        а не ждёт, пока про него вспомнят.
        """
        if self.store is None:
            return
        self.store.save_session(
            self.id,
            label=self.spec.label,
            config=asdict(self.spec),
            created_at=self.created_at,
            context_length=self.context_length,
        )

    def forget(self) -> None:
        """Забывает разговор целиком — историю, сводки, рабочую память
        и состояние задачи.

        Сводка заменяла начало истории; истории больше нет, и покрывать ей
        нечего. Оставленная, она накрыла бы собой начало **следующего**
        разговора в этом же чате: `summary_cover` зажат длиной истории, и на
        отросшей заново истории мёртвая сводка снова стала бы действующей.

        С рабочей памятью хуже: у неё и зажима такого нет — врезка встаёт
        в промпт, пока в памяти есть хоть одна запись. Забытый разговор
        оставил бы свои цели и ограничения следующему, и тот отвечал бы
        по ним.

        А долговременная память не трогается: чат ей не владелец, а читатель,
        и «забыть этот разговор» не значит «забыть, кто с тобой говорит».

        А происхождение (`branch`) не трогается: это не содержимое разговора,
        а то, откуда чат взялся. «Забыть» здесь нечего — ветка, забывшая свою
        историю, осталась веткой того же родителя, и пометка про это
        по-прежнему правда. Поэтому путей очистки у родства два, а не три:
        удаление чата и очистка базы.
        """
        self.history.clear()
        self.summaries = []
        self.working = []
        # И состояние задачи — тем же порядком и по тому же доводу, что
        # рабочая память: зажима по длине истории у блока задачи нет, и
        # забытый разговор оставил бы следующему «этап: проверка» первой же
        # строкой. Задачи не стало — значит, снова планирование.
        self.task = blank_task()
        # Журнал уходит вместе с задачей и одним методом (`clear_task`):
        # летопись переходов без разговора, в котором они случились,
        # рассказывала бы про чужую задачу.
        self.task_log = []
        if self.store is not None:
            self.store.save_summaries(self.id, [])
            self.store.clear_working(self.id)
            self.store.clear_task(self.id)
        self.persist()

    def usage_summary(self) -> dict | None:
        """Итог по чату: вход, выход, всего, стоимость и число ответов с числами.

        Считается здесь, а не в браузере: иначе плитки и лента — два источника
        правды, и разъезжаются они молча. Колонки в базе у неё нет: она
        выводится из `messages.metrics` и `summaries.metrics` — из вторых
        потому, что вызов на сжатие тоже уехал в модель и тоже оплачен.
        Журнала этапа среди слагаемых нет: этап переключает человек
        нажатием, к модели этот переход не ходит, и своей цены у него
        не бывает вовсе.

        Реплика без метрик и поле с `None` **пропускаются**, а не считаются
        нулём: неизвестное и ноль на экране обязаны выглядеть по-разному —
        чат без чисел даёт `None`, и клиент рисует прочерк.
        """
        totals: dict = {name: None for name in USAGE_FIELDS}
        answers = 0

        def add(metrics) -> bool:
            """Прибавляет один набор метрик. False — чисел в нём не нашлось."""
            if not isinstance(metrics, dict):
                return False
            counted = False
            for name in USAGE_FIELDS:
                value = _usage_number(metrics.get(name))
                if value is None:
                    continue
                totals[name] = value if totals[name] is None else totals[name] + value
                counted = True
            return counted

        for turn in self.history:
            if turn.role != "assistant":
                continue
            # Ответ, у которого метрики есть, но чисел в них нет, обменом
            # не считается: иначе делитель рос бы на пустом месте.
            if add(turn.metrics):
                answers += 1

        # Второй проход — по сводкам. Вызов на сжатие тоже уехал в модель и
        # тоже оплачен: экономия, не вычитающая стоимость сжатия, — враньё.
        # Сводки живут не в истории, поэтому складываются отдельно; карточкой
        # в ленте сжатие не становится и числа сообщений не растит.
        for item in self.summaries:
            if add(item.get("metrics")):
                answers += 1

        if not answers:
            return None
        if totals["cost_usd"] is not None:
            # Копейки от сложения float'ов: цена показывается до шестого знака.
            totals["cost_usd"] = round(totals["cost_usd"], 8)
        return totals

    def transcript(self) -> list[dict]:
        """Ровно реплики диалога. Системного промпта здесь нет: он конфиг,
        а не реплика, и виден в панели полем `system`."""
        return [asdict(turn) for turn in self.history]

    def as_dict(self, *, with_transcript: bool = False) -> dict:
        data = spec_as_dict(
            self.spec,
            agent_id=self.id,
            history_len=len(self.history),
            usage_total=self.usage_summary(),
            created_at=self.created_at,
            last_used_at=self.last_used_at,
            busy=self.busy,
            branch=self.branch,
            task=self.task,
        )
        if with_transcript:
            data["transcript"] = self.transcript()
            # Журнал этапа едет вместе со стенограммой, а не со списком
            # слева: в списке он никому не нужен, а растёт он с каждым
            # обменом. Своей ручки у него нет по тому же доводу, что
            # и у самого состояния, — он приезжает с чатом.
            data["task_log"] = self.task_log_view()
        return data

    def task_log_view(self) -> list[dict]:
        """Журнал этапа так, как его ждёт экран. Одной формой на оба пути
        наружу — и на сам чат, и на кадр `done` обмена: две сборки одного
        списка разошлись бы молча, и после обмена на экране стояло бы одно,
        а после перезагрузки другое."""
        return [
            {name: item[name] for name in ("seq", "stage_from", "stage_to", "who", "ok", "at")}
            for item in self.task_log
        ]

    # --- обмен ---------------------------------------------------------------

    async def ask(self, user_text: str) -> AsyncIterator[dict]:
        """Один обмен: вопрос → поток событий → запись в историю.

        События: `compressing`, `start`, `reasoning`, `delta`, `metrics`,
        `error`, `done`.

        `compressing` — «шаг идёт прямо сейчас»: обмен знает ровно одну
        паузу до первого токена — сворачивание, — и шлётся событие ровно
        тогда, когда сворачивание правда будет. Строка состояния обещает
        паузу, которая случится.

        Обращение к модели на обмен ровно одно (плюс сворачивание, если его
        выбрали): этап переключает человек нажатием на полосу, и к модели
        переход не ходит вовсе.

        История не трогается до конца обмена — откат получается по построению:

        * ответа не случилось вовсе → в историю не пишется ничего, вопрос
          возвращается в событии `done` полем `question`;
        * ответ частичный (обрыв, отмена) → пишутся обе реплики, у ответа
          проставлен `error`.
        """
        if self._lock.locked():
            raise AgentBusyError(f"агент {self.id} уже занят: дождитесь текущего ответа")

        async with self._lock:
            self._cancel = asyncio.Event()
            cancel = self._cancel
            self.last_used_at = time.time()

            # Слепок конфига на весь обмен. Промпт и тело запроса собираются
            # в двух разных точках, и между ними стоит `yield` события `start`:
            # правка панели, попавшая туда, дала бы смешанный запрос — новую
            # модель со старым системным промптом. Сейчас через этот `yield`
            # никто не приостанавливается, но держится это на устройстве
            # доставки событий, а не на самом обмене: ограничат очередь или
            # добавят один `await` — и окно откроется молча. Со слепком
            # «текущий вызов идёт целиком на одном конфиге» верно
            # по построению, а не по совпадению.
            spec = copy_spec(self.spec)
            context_length = self.context_length

            # Сворачивание — лениво и **до** сборки промпта: этот же обмен
            # уедет уже сжатым, и экономия видна во входных токенах его
            # собственного ответа, а не следующего.
            #
            # Перед ним — событие о том, что оно будет: вызов идёт к модели
            # раньше самого ответа, и без события клиент узнал бы о паузе,
            # только когда она уже кончилась. Шлём ровно тогда, когда вызов
            # правда состоится, — решает это один код (`compress_plan`), и он
            # же зовёт сам вызов: обещание строки состояния держится не
            # совпадением двух условий, а тем, что условие одно.
            #
            # Сворачивание — единственная пауза обмена, и потому
            # единственное, про что здесь решают: к модели на обмен идёт
            # один вызов, а этап человек переключает сам, мимо обмена.
            if self.compress_plan(spec) is not None:
                yield {"type": "compressing", "strategy": "summary"}
                await self.compress(spec, context_length)
            cut, _ = self.context_cut(spec)

            # Долговременная память читается **один раз на обмен** и уезжает
            # и в сборку промпта, и в оба слота. Прочитай их по отдельности —
            # запись, добавленная из соседней вкладки между этими двумя
            # чтениями, попала бы в промпт, но не в номера врезок (или
            # наоборот), и просмотр промпта подписал бы чужие роли.
            #
            # Читается после служебного вызова, а не до: сворачивание идёт
            # к модели и длится сколько угодно, и память, записанную за это
            # время, честнее взять свежей.
            memory = self.memory_items(spec)
            # Профиль — тем же порядком и по тому же доводу: прочитан один
            # раз на обмен и уезжает и в промпт, и в номера врезок. Он
            # заводит собой системное сообщение, и прочитанный дважды
            # развёл бы промпт с номерами сильнее любой врезки.
            profile = self.profile_items()
            # И состояние задачи — тем же порядком и по тому же доводу:
            # прочитано один раз на обмен и уезжает и в промпт, и в номер
            # врезки. Соседняя вкладка вправе переключить этап посреди
            # обмена, и прочитанное дважды развело бы промпт с кадром `start`.
            task = self.task_items()

            prompt = self.build_prompt(
                user_text, spec=spec, memory=memory, profile=profile, task=task
            )

            # `summary_at` — место врезки стратегии в промпте, `memory_at`
            # и `working_at` — места врезок памяти; `None` у любого из них
            # значит, что этой врезки в промпте нет. Сам промпт клиент и так
            # получает; без этих чисел он различал бы врезки разбором текста,
            # то есть повторял бы у себя устройство `build_prompt` и
            # расходился бы с ним молча. Подписывает роли в просмотре промпта
            # тоже сервер, а не догадка клиента по первой строке сообщения.
            #
            # Слота три, потому что врезок в одном промпте бывает три:
            # оба слоя памяти едут при любой стратегии и ни одну из них
            # не отменяют. Считает их все `prompt_slots` — одним ответом и
            # по тому же порядку, каким промпт и собран: перечисли их здесь
            # по одному, и четвёртая врезка приехала бы без номера.
            # Состояние задачи уезжает здесь же и тем же кадром: служебный
            # вызов уже отработал, и этап в кадре — **новый**. Полоса в шапке
            # перекрашивается по нему, то есть раньше первого токена ответа:
            # спроси клиент состояние отдельной ручкой, и переход был бы
            # виден только после обмена, а к этому обмену он уже относится.
            yield {
                "type": "start",
                "resolved_messages": prompt,
                "question": user_text,
                **self.prompt_slots(spec, memory, profile, task),
                "strategy": spec.strategy,
                "task": task_view(task),
            }

            text = ""
            reasoning = ""
            final_metrics: dict | None = None
            failure: str | None = None
            cancelled = False

            try:
                stream = stream_completion(
                    spec, prompt_override=prompt, context_length=context_length
                )
                async with contextlib.aclosing(stream):
                    async for chunk in stream:
                        kind = chunk["type"]
                        if kind == "delta":
                            text += chunk["text"]
                            yield chunk
                        elif kind == "reasoning":
                            reasoning += chunk["text"]
                            yield chunk
                        elif kind == "metrics":
                            yield chunk
                        elif kind == "error":
                            failure = chunk["message"]
                            final_metrics = chunk["metrics"]
                            yield chunk
                        elif kind == "done":
                            text = chunk["text"]
                            reasoning = chunk.get("reasoning") or reasoning
                            final_metrics = chunk["metrics"]
                        if cancel.is_set():
                            cancelled = True
                            break
            except MissingKeyError as exc:
                failure = str(exc)
                yield {"type": "error", "message": failure, "metrics": None}
            except asyncio.CancelledError:
                # Клиент ушёл: частичный ответ всё равно записываем — он уже
                # оплачен, а следующий вопрос должен видеть, чем кончилось.
                self._commit(user_text, text, "вызов прерван", reasoning, final_metrics)
                raise
            except Exception as exc:  # noqa: BLE001 — падает обмен, процесс живёт
                failure = f"{type(exc).__name__}: {exc}"
                yield {"type": "error", "message": failure, "metrics": None}

            if cancelled and failure is None:
                failure = "генерация отменена"

            # Сколько реплик не уехало дословно — знание агента, а не
            # провайдера, и место ему рядом с числами обмена: строка под
            # ответом покажет его там же, где входные токены, которые оно
            # уменьшило. В суммы по чату ключ не идёт — их считает USAGE_FIELDS.
            #
            # Ключ у каждой стратегии свой, потому что говорят они разное:
            # сводка начало **заменила** — его видно в промпте запроса, —
            # а окно его **отбросило**. Одно слово на оба случая соврало бы
            # про какой-нибудь из них.
            if cut and isinstance(final_metrics, dict):
                final_metrics = {**final_metrics, CUT_METRIC[spec.strategy]: cut}

            committed = self._commit(user_text, text, failure, reasoning, final_metrics)

            done: dict = {
                "type": "done",
                "text": text,
                "reasoning": reasoning,
                "metrics": final_metrics,
                "cancelled": cancelled,
                "error": failure,
                "committed": committed,
                # Состояние задачи и его журнал — тем же кадром: этап мог
                # переключить человек из соседней вкладки, пока шёл ответ,
                # и полоса обязана прийти в согласие с базой без единого
                # лишнего запроса.
                "task": task_view(self.task),
                "task_log": self.task_log_view(),
            }
            if not committed:
                # Обмена не было: вопрос нельзя оставлять в ленте клиента —
                # он вернётся в поле ввода и его можно будет повторить.
                done["question"] = user_text
            yield done

    def _commit(
        self,
        user_text: str,
        answer: str,
        failure: str | None,
        reasoning: str = "",
        metrics: dict | None = None,
    ) -> bool:
        """Пишет обмен в историю. Возвращает False, если писать было нечего."""
        if not answer.strip():
            return False

        # Вопрос и ответ ложатся в базу парой, одной транзакцией: иначе,
        # умри процесс между ними, в базе остался бы вопрос без ответа.
        with self.store.tx() if self.store is not None else contextlib.nullcontext():
            self.remember("user", user_text, persist=False)
            # Ответ, оборванный на середине, всё равно часть диалога — но помечен:
            # следующий вопрос должен видеть, что предыдущий ответ неполный.
            self.remember(
                "assistant", answer, error=failure, reasoning=reasoning, metrics=metrics
            )
        return True

    def take_last_exchange(self) -> Exchange | None:
        """Снимает последнюю пару «вопрос — ответ»: перегенерация обязана
        **заменить** ответ, а не дописать второй, и модель должна увидеть тот же
        контекст. Снятое возвращается целиком — если вызов не отдаст ни токена,
        `restore` кладёт обратно и вопрос, и прежний ответ.

        В базу снятое не пишется: пока перегенерация не удалась, в файле лежит
        ровно исходная пара, а удачная перепишет историю целиком. Ни дублей,
        ни дыр в нумерации ни в одном исходе.
        """
        if [turn.role for turn in self.history[-2:]] != ["user", "assistant"]:
            return None
        taken = self.history[-2:]
        del self.history[-2:]
        return Exchange(question=taken[0].content, turns=taken, depth=len(self.history))

    def restore(self, exchange: Exchange) -> bool:
        """Кладёт снятую пару обратно, если её место никто не занял. Записался
        новый обмен — перегенерация удалась (или оборвалась с частичным ответом,
        что тоже записано), и класть старое поверх нельзя: в ленте было бы два
        ответа на один вопрос."""
        if len(self.history) != exchange.depth:
            return False
        self.history.extend(exchange.turns)
        # В норме база с момента снятия не менялась, но если новый обмен успел
        # записаться и откатиться — файл обязан сойтись с памятью.
        self.persist()
        return True


def spec_as_dict(
    spec: AgentSpec,
    *,
    agent_id: str,
    history_len: int,
    created_at: float,
    last_used_at: float,
    busy: bool = False,
    usage_total: dict | None = None,
    branch: dict | None = None,
    task: dict | None = None,
) -> dict:
    """Конфиг чата так, как его ждут список слева и панель справа.

    Функция, а не метод: тем же форматом описывается чат, которого сейчас нет
    в памяти. Клиент не должен различать «поднято» и «лежит в базе».
    """
    data = {
        "id": agent_id,
        "label": spec.label,
        "model": spec.model,
        "stop": spec.stop,
        "response_format": spec.response_format,
        "extra_body": spec.extra_body,
        "system": spec.system,
        # Длина истории — она же число сообщений в плитке справа: одна реплика,
        # хоть вопрос, хоть ответ, — одно сообщение. Сжатие её не растит, сводка
        # живёт вне истории. У чата, которого нет в памяти, то же число считает
        # SQL (`app/store.py`), и клиенту не приходится различать эти два случая.
        "history_len": history_len,
        # Итог по чату едет тем же путём: у выгруженного чата сводки нет,
        # и это `None`, то есть прочерк, а не ноль.
        "usage_total": usage_total,
        "busy": busy,
        # Происхождение: `{parent_id, forked_at}` у ветки, `None` у чата,
        # заведённого сам по себе. Имени родителя здесь нет — только id:
        # имя по нему находит тот, кто рисует список, у него все чаты и так
        # на руках, и переименование родителя видно сразу.
        "branch": branch,
        # Состояние задачи: этап, текущий шаг и ожидаемое действие. Едет
        # с чатом, а не своей ручкой, — полоса этапов стоит в шапке и
        # рисуется тем же ответом, каким рисуется сама лента. У чата,
        # которого не трогали, здесь умолчание, а не `None`: этап есть
        # у задачи всегда.
        "task": task_view(blank_task() if task is None else dict(task)),
        "created_at": created_at,
        "last_used_at": last_used_at,
    }
    # Параметры сэмплирования уходят наружу как есть, включая None:
    # панель справа отличает «не задано» от нуля, и ей нужно и то и другое.
    for name in SAMPLING_FIELDS:
        data[name] = getattr(spec, name)
    # То же и про управление контекстом: пустое окно памяти значит «сжатия
    # нет», и панель обязана показать именно пустое поле, а не ноль.
    for name in CONTEXT_FIELDS:
        data[name] = getattr(spec, name)
    return data


_SPEC_FIELDS = {f.name for f in fields(AgentSpec)}


def spec_from_config(config: dict, *, fallback: AgentSpec) -> AgentSpec:
    """Конфиг из базы обратно в `AgentSpec`.

    Незнакомые ключи отбрасываются молча: базу мог записать сервер другой
    версии, и падать на чужом поле — значит потерять сохранённый диалог.
    """
    known = {key: value for key, value in (config or {}).items() if key in _SPEC_FIELDS}
    if not known.get("model"):
        return fallback
    known.setdefault("label", fallback.label)
    return AgentSpec(**known)
