"""Датаклассы дня — единственное, что импортирует day.py.

`AgentSpec` описывает ровно то, что уходит в запрос к OpenRouter, и ловит
опечатку в ключе здесь, а не на живом прогоне за деньги. С Дня 6 это ещё и
конфиг агента: колонка сценария и агент — одно и то же, поэтому спавн сотни
агентов с разными конфигами — это сотня `AgentSpec`, а не сотня процессов.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class AgentSpec:
    """Конфиг одного агента. Он же — одна колонка split-screen.

    Всё, чем один агент отличается от другого при спавне: модель, семплирование,
    системный промпт, стартовые сообщения и лимит памяти. Датакласс намеренно
    без методов: спавн сотни агентов — это сотня дешёвых `replace(spec, ...)`.
    """

    label: str
    """Заголовок колонки в UI."""

    model: str
    """id модели OpenRouter, например "meta-llama/llama-3.1-8b-instruct"."""

    messages: list[dict]
    """Сообщения в формате OpenAI chat: [{"role": "user", "content": "..."}]."""

    temperature: float | None = None
    max_tokens: int | None = None
    stop: list[str] | None = None
    response_format: dict | None = None

    repeats: int = 1
    """Сколько раз подряд прогнать эту колонку одним и тем же запросом.

    Дефолт 1 — колонка делает ровно один вызов, и поток событий у неё такой же,
    как был до появления повторов. Больше одного нужно там, где эффект
    статистический и на одном ответе не виден: День 4 сравнивает температуры,
    а разброс проявляется только на нескольких прогонах одного запроса.

    Повторы идут последовательно: важна предсказуемость и цена, а не скорость.
    Каждый прогон стенд рисует в ленте отдельным блоком со своими метриками.
    Под колонкой стенд считает долю уникальных ответов, а судье отдаёт
    все ответы серии.
    Цена растёт кратно: repeats=3 — это втрое дороже и втрое дольше.
    """

    depends_on: str | None = None
    """label другой сессии этого же сценария.

    Эта сессия стартует только после того, как отработает та, а её вывод
    подставляется вместо {{depends_on}} в любом content этой сессии.
    День 3: модель сначала пишет промпт, потом стенд его применяет.
    """

    note: str = ""
    """Подпись под колонкой: что именно тут показываем."""

    extra_body: dict = field(default_factory=dict)
    """Дополнительные поля запроса к OpenRouter (seed, provider.order и т.п.).

    Мержится поверх тела запроса. app/llm.py уже добавляет
    provider.require_parameters = true — переопределять не нужно,
    но можно дополнить: {"provider": {"allow_fallbacks": False}}.
    """

    system: str = ""
    """Системный промпт агента, если его нет в `messages`.

    Нужен агентам, которых собирают не из сценария, а по конфигу: у них
    `messages` пустые, и системную инструкцию класть больше некуда. Если
    в `messages` уже есть сообщение с ролью system, это поле игнорируется —
    иначе агент получил бы две системные инструкции подряд.
    """

    history_limit: int | None = None
    """Сколько последних сообщений истории уходит в окно запроса.

    None — дефолт агента (`app.agent.DEFAULT_HISTORY_LIMIT`). 0 — агент без
    памяти: каждый вопрос уходит в модель как первый. Считается в сообщениях,
    а не в парах: 8 — это четыре обмена.

    Это лимит **окна**, а не хранилища: в стенограмме агента остаётся всё,
    что было (до жёсткого потолка `app.agent.MAX_STORED_MESSAGES`), просто
    в модель уезжает только хвост.
    """


# День 6 переименовал Session в AgentSpec: колонка сценария и есть конфиг
# агента, и называть её «сессией» стало неправдой. Алиас оставлен намеренно —
# day.py дней 1–5 импортирует `Session` и должен продолжать работать без правок.
Session = AgentSpec


@dataclass
class Scenario:
    """Один сценарий стенда. day.py отдаёт список таких сценариев — SCENARIOS.

    Отдельного идентификатора у сценария нет: в дне их единицы, и стенд
    адресует сценарий его позицией в SCENARIOS.
    """

    title: str
    description: str
    """Показывается до нажатия «Старт» — что это за демонстрация.

    Уходит модели-судье как контекст эксперимента, поэтому эталонных ответов
    и предсказаний «кто ошибётся» здесь быть не должно: это описание
    демонстрации, а не её разбор. Разбор — в README.md.
    """

    sessions: list[AgentSpec]

    layout: str = "split"
    """split | single."""

    judge_questions: list[str] = field(default_factory=list)
    """Вопросы задания дня, своими словами — на них отвечает модель-судья.

    После того как отработали все колонки, стенд делает один дополнительный
    вызов к отдельной модели и стримит её ответ в блок «Вердикт» под колонками.
    Судье уходят эти вопросы и description сценария, а по каждой колонке —
    label, note, отличающие её параметры, метрики и полный ответ. Промпты
    колонок судье не отправляются: он смотрит на результат, а не на задание.

    Пустой список (по умолчанию) — блока «Вердикт» нет и вызова нет: день,
    который ничего не сравнивает, не должен платить за судью.
    """

    judge_model: str | None = None
    """Модель-судья. None — дефолт стенда (app.main.JUDGE_MODEL).

    Весь смысл в том, что судит **другая** модель, а не одна из колонок.
    Совпадение с моделью колонки не запрещено, но стенд помечает его в UI.
    """
