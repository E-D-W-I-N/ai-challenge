"""Конфиг агента: всё, чем один чат отличается от другого.

Сотня агентов с разными конфигами — это сотня `AgentSpec`, а не сотня
процессов. Датакласс намеренно без методов: `replace(spec, ...)` обязан
оставаться дешёвым.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class AgentSpec:
    label: str
    model: str
    """id модели OpenRouter, например "meta-llama/llama-3.1-8b-instruct"."""

    system: str = ""
    """Системный промпт. Дом у него ровно один — это поле."""

    # Параметры сэмплирования. None значит «не отправлять параметр», а не
    # «отправить ноль»: с provider.require_parameters=true каждый заданный
    # параметр сужает список провайдеров, готовых обслужить вызов.
    temperature: float | None = None
    max_tokens: int | None = None
    top_p: float | None = None
    top_k: int | None = None
    min_p: float | None = None
    repetition_penalty: float | None = None
    presence_penalty: float | None = None
    frequency_penalty: float | None = None

    stop: list[str] | None = None
    response_format: dict | None = None

    # Управление контекстом. Идиом тот же, что у сэмплирования: None — «не
    # делать», а не «делать с нулём». `keep_last is None` значит, что резать
    # нечем и в модель уезжает вся история, как в Дне 8. Булева переключателя
    # нет намеренно: в Python True — это int, и разбор полей его отбрасывает
    # (`_optional_field`, app/main.py).
    strategy: str = "full"
    """Сколько реплик уезжает в модель **дословно**: `full` — вся история,
    `window` — последние `keep_last`, остальное отброшено, `summary` — сводка
    начала плюс последние `keep_last`. Три варианта, и все три теперь про одно
    и то же число: врезку рабочей памяти отсюда убрали вовсе — её ведёт агент
    при любом варианте, и выбирать её переключателем стало нечем.

    Строка, а не `Literal` и не `bool`: `Literal` не по зубам разбору
    round-trip проверки, а `bool` отбрасывается разбором полей. Значение не
    из списка ручки не пропустят (`_choice_field`, app/main.py), а
    записанное чужой версией сервера читается как `full` — обрезка бывает
    только выбранная."""

    keep_last: int | None = None
    """Сколько последних реплик уезжает в модель как есть — хвост окна и хвост
    сводки это одно и то же число."""

    compress_every: int | None = None
    """Порог: сводка пересобирается, когда несвёрнутых реплик старше окна
    накопилось столько. None — сжатие не запускается никогда."""

    memory: str = "on"
    """Ведёт ли агент память в этом чате: `on` — служебный вызов идёт на
    каждом обмене, а записи обоих слоёв встают врезками в промпт при **любой**
    стратегии; `off` — не идёт и не встают.

    Один выключатель на запись и на показ, а не два: чат, которому агент
    ничего не выписывает, и чат, которому не показывают выписанное, — это
    один и тот же чат, «здесь запоминать нечего». Два выключателя развели бы
    его на четыре состояния, из которых два бессмысленны.

    Выключатель на чат, а не на базу: слой глобальный, и рядом с чатом,
    который его видит, должен существовать чат, который его не видит, —
    иначе «как это влияет на ответы» не с чем сравнить.

    Строка, а не `bool`, по тому же доводу, что у `strategy`: в Python
    `True` — это `int`, и разбор полей его отбрасывает (`_optional_field`,
    app/main.py). Умолчание — `on`: на свежей базе память пуста, а пустая
    память неотличима от отсутствующей, и включённый выключатель ничего
    не меняет. Значение не из списка ручки не пропустят (`_choice_field`),
    а записанное чужой версией сервера читается как `on` — зеркало того,
    как незнакомая стратегия читается как `full`.
    """

    extra_body: dict = field(default_factory=dict)
    """Дополнительные поля запроса (seed, provider.order и т.п.). Мержится
    поверх тела; `provider.require_parameters` уже стоит в app/llm.py, там же
    `plugins` мержатся по `id`: выключенный `context-compression` уцелеет
    рядом с вашим, а названный тем же `id` — победит."""


STRATEGIES = ("full", "window", "summary")
"""Чем управлять контекстом — список целиком. Порядок тот же, в каком варианты
стоят в переключателе панели: от «ничего не делаем» к «делаем больше всего».

Их стало три: `facts` ушёл. Выписку состояния задачи агент ведёт теперь при
любом варианте — выбирать её отдельным пунктом переключателя значило бы
предлагать выключить память, притворяясь, что речь про обрезку. Все три
оставшихся про одно и то же: сколько реплик уедет в модель дословно."""

CONTEXT_NUMBERS = ("keep_last", "compress_every")
"""Числовая половина управления контекстом: разбирается как сэмплирование —
целое или null, где null значит «не делать»."""

MEMORY_CHOICES = ("on", "off")
"""Положения выключателя долговременной памяти. Умолчание — первое."""

MEMORY_KINDS = ("profile", "decision", "knowledge")
"""Какого рода бывает запись долговременной памяти: профиль (кто говорит),
решение (о чём договорились), знание (что выяснили). Три, потому что задание
просит разделить информацию минимум на три типа, — но разделение это внутри
третьего слоя, а не вместо слоёв."""

MEMORY_LABELS = {"profile": "профиль", "decision": "решение", "knowledge": "знание"}
"""Русские подписи родов — одни и те же во врезке и во вкладке. Две таблицы
разошлись бы молча: в промпте у модели стояло бы одно слово, а на экране
у пользователя — другое."""

WORKING_KINDS = ("goal", "limit", "decision", "question")
"""Какого рода бывает запись рабочей памяти: цель, ограничение, решение,
открытый вопрос. Роды взяты из самой модели слоя — рабочая память хранит
**состояние задачи**, — а не выдуманы рядом с ней: разделение внутри слоя
обязано называть то же, что называет сам слой."""

WORKING_LABELS = {
    "goal": "цель",
    "limit": "ограничение",
    "decision": "решение",
    "question": "открытый вопрос",
}
"""Русские подписи родов рабочей памяти — одна карта на врезку в промпт,
на ответ модели и на вкладку. Довод тот же, что у `MEMORY_LABELS`: второй
таблицей подписи разъехались бы молча. Подписью же запись и уезжает в модель
(«цель: собрать ТЗ»), поэтому ими же модель и отвечает — просить её говорить
токенами значило бы держать два словаря на один слой."""

RECORD_AUTHORS = ("agent", "human")
"""Кто записал: служебный вызов или человек. Не украшение списка, а инвариант:
служебный вызов правит только свои записи, а чужую не трогает ни правкой, ни
удалением — иначе первая же правка руками исчезла бы на следующем обмене.

Список один на **оба** редактируемых слоя — и рабочую память, и
долговременную: правило у них общее, пишут в них обе стороны, и вторая копия
списка разошлась бы с первой ровно в том месте, ради которого её и писали."""

CONTEXT_FIELDS = ("strategy", *CONTEXT_NUMBERS, "memory")
"""Поля управления контекстом. В тело запроса они не уезжают ни одним ключом:
сжатие наше, а не провайдерское, — его плагин выключен на каждом вызове.
Стратегия первой: она решает, значат ли что-нибудь два числа за ней.
Выключатель памяти последним: он ортогонален всем трём — память ведётся
(или не ведётся) при любой стратегии и ни одну из них не отменяет."""
