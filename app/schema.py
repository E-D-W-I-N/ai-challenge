def blank_task() -> dict:
    """Состояние задачи чата, которого никто не трогал. Функцией, а не
    константой: словарь отдаётся наружу и правится на месте, а общий на всех
    объект развёл бы два чата одним."""
    return {"stage": TASK_STAGE_DEFAULT, "step": "", "expecting": ""}


CONTEXT_FIELDS = ("workflow", "strategy", *CONTEXT_NUMBERS)
"""Поля управления контекстом. В тело запроса они не уезжают ни одним ключом:
сжатие наше, а не провайдерское, — его плагин выключен на каждом вызове.
Стратегия первой из трёх оставшихся: она решает, значат ли что-нибудь два
числа за ней.

`workflow` стоит здесь по образцу снесённого выключателя памяти: строка
из закрытого списка, а дальше ниткой самого списка — `spec_as_dict`,
`PATCHABLE`, разбор на границе. Управлением контекстом он при этом не
является: он решает, есть ли у чата задача вообще, а не что делать
с историей. Место общее потому, что нитка общая, и второй такой же нитки
рядом заводить незачем.

Выключателя памяти здесь больше нет: память ведётся всегда и в каждом чате.
Он был заведён затем, чтобы рядом с чатом, который память видит, существовал
чат, который её не видит, — и сравнение «как это влияет на ответы» переехало
туда, где оно честнее: пустая память против непустой. А заодно исчезло
состояние, в котором агент платит за вызов, чей ответ некуда положить."""

