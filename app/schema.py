"""Конфиг агента — единственное, что импортирует day.py.

`AgentSpec` описывает ровно то, что уходит в запрос к OpenRouter, и ловит
опечатку в ключе здесь, а не на живом вызове за деньги. Он же конфиг агента:
спавн сотни агентов с разными конфигами — это сотня `AgentSpec`, а не сотня
процессов.

Датакласс намеренно без методов: `replace(spec, ...)` обязан оставаться
дешёвым.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class AgentSpec:
    """Конфиг одного агента.

    Всё, чем один агент отличается от другого при спавне: модель, параметры
    сэмплирования, системный промпт, лимит памяти и место в списке слева.
    """

    label: str
    """Имя агента в списке слева."""

    model: str
    """id модели OpenRouter, например "meta-llama/llama-3.1-8b-instruct"."""

    messages: list[dict] = field(default_factory=list)
    """Стартовые сообщения в формате OpenAI chat.

    Агентам ростера не нужны: их системная часть лежит в `system`, а вопрос —
    в `draft`. Поле остаётся ради `Session`: day.py дней 1–5 собирает колонки
    через него, и агента по-прежнему можно завести с готовой заготовкой
    диалога — например с парой примеров «вопрос — ответ».
    """

    system: str = ""
    """Системный промпт агента, если его нет в `messages`.

    Если в `messages` уже есть сообщение с ролью system, это поле игнорируется —
    иначе агент получил бы две системные инструкции подряд.
    """

    draft: str = ""
    """Черновик вопроса: подставляется в поле ввода при открытии агента.

    Сам не отправляется. У агентов дней 1–5 здесь лежит вопрос того дня:
    его видно, можно поправить и отправить — отправка всегда решение
    пользователя, а не наше.
    """

    group: str = ""
    """Заголовок группы в списке слева: «День 1», «День 2» и так далее.

    Пустая группа — обычный чат пользователя. По этому же признаку «Очистить
    все чаты» отличает чаты от агентов ростера: ростер не трогается.
    """

    note: str = ""
    """Подпись под именем агента: что это за агент и откуда он взялся."""

    # --- параметры сэмплирования ------------------------------------------
    #
    # Все до одного необязательные, и None значит «не отправлять параметр»,
    # а не «отправить ноль». Пустое поле в панели справа — это None.
    # Помнить про provider.require_parameters=true: каждый заданный параметр
    # сужает список провайдеров, готовых обслужить вызов.

    temperature: float | None = None
    max_tokens: int | None = None
    top_p: float | None = None
    top_k: int | None = None
    min_p: float | None = None
    repetition_penalty: float | None = None
    presence_penalty: float | None = None
    frequency_penalty: float | None = None

    stop: list[str] | None = None
    response_format: dict | None = None

    extra_body: dict = field(default_factory=dict)
    """Дополнительные поля запроса к OpenRouter (seed, provider.order и т.п.).

    Мержится поверх тела запроса. app/llm.py уже добавляет
    provider.require_parameters = true — переопределять не нужно,
    но можно дополнить: {"provider": {"allow_fallbacks": False}}.
    """

    history_limit: int | None = None
    """Сколько последних сообщений истории уходит в окно запроса.

    None — дефолт агента (`app.agent.DEFAULT_HISTORY_LIMIT`). 0 — агент без
    памяти: каждый вопрос уходит в модель как первый. Считается в сообщениях,
    а не в парах: 8 — это четыре обмена.

    Это лимит **окна**, а не хранилища: в стенограмме агента остаётся всё,
    что было (до жёсткого потолка `app.agent.MAX_STORED_MESSAGES`), просто
    в модель уезжает только хвост.
    """


# Поля прошлых дней, которых в конфиге агента больше нет: сценарии выпилены
# вместе с сериями и зависимостями между колонками.
_RETIRED_FIELDS = ("repeats", "depends_on")


def Session(*args, **kwargs) -> AgentSpec:  # noqa: N802 — это имя типа, а не функции
    """Конфиг колонки, как её объявляли дни 1–5. Совместимость, не новый API.

    День 6 переименовал `Session` в `AgentSpec`: «сессия» перестала быть
    правдой, когда у объекта появились история и метод обмена. Имя оставлено,
    потому что конфиги ростера взяты из `day.py` дней 1–5, и они объявляют
    колонки через него — вместе с `repeats` и `depends_on`, которых в стенде
    больше нет. Эти два поля здесь молча отбрасываются: код прошлых дней
    должен продолжать собираться, не заставляя нас держать в конфиге
    механизмы, которых нет.

    Полной совместимости с `day.py` прошлых дней это не даёт и дать не может:
    они импортируют ещё и `Scenario`, а сценарии удалены. Настоящее чтение
    старых дней живёт в `checks/_daysrc.py` со своим шимом — и оно на каждом
    прогоне проверок сверяет ростер с ветками.
    """
    for retired in _RETIRED_FIELDS:
        kwargs.pop(retired, None)
    return AgentSpec(*args, **kwargs)
