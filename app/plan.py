def _one_step(raw) -> dict:
    """Один шаг из присланного — или `PlanError` с назвавшей себя причиной.

    Причины разные у заголовка и у статуса намеренно: «план не записан»
    без указания, что именно не так, модель исправляет наугад.
    """
    title = raw.get("title") if isinstance(raw, dict) else None
    if not isinstance(title, str) or not title.strip():
        raise PlanError("у шага нет заголовка title или он пустой")
    status = raw.get("status")
    if status not in STEP_STATUSES:
        raise PlanError(
            f"у шага «{title.strip()}» статус {status!r}, "
            f"а бывает только {', '.join(STEP_STATUSES)}"
        )
    return {"title": title.strip(), "status": status}


def _new_steps(args) -> list[dict]:
    """Список шагов из аргументов вызова. Любая кривизна — `PlanError`
    с причиной внутри; собирает её в директиву `apply`, где известно имя
    инструмента и текущий план."""
    raw = (args or {}).get("steps")
    if not isinstance(raw, list) or not raw:
        raise PlanError("список шагов пустой, а план без шагов — это не план")
    steps = [_one_step(item) for item in raw]
    running = [step for step in steps if step["status"] == "in_progress"]
    if len(running) > 1:
        # «Ровно один in_progress» — правило промпта, а не кода: свежий план
        # «все pending» законен. Кода здесь ровно столько, чтобы не было
        # двух текущих шагов сразу: тогда `current_step` назвал бы один,
        # а модель вела бы другой.
        raise PlanError(
            f"in_progress отмечено шагов: {len(running)}, а в работе бывает только один"
        )
    return steps


def _updated(plan: dict, args) -> tuple[dict, str]:
    """`update_plan`: переписывает список шагов целиком.

    Неутверждённый план модель переписывает свободно — это и есть
    планирование. **Утверждённый тоже**: отметки, возврат шага в `pending`,
    новый шаг — это ведение работы, а не подмена плана, и флаг `approved`
    при этом не снимается. Запрещено это ровно в одном состоянии —
    у завершённой задачи, и там переоткрывает человек кнопкой.
    """
    steps = _new_steps(args)
    # Список стал **короче**, чем был у утверждённого плана, — утверждение
    # снимается, и человек утверждает заново.
    #
    # Иначе получается вот что: человек утвердил три шага, модель присылает
    # список из одного шага со статусом `done` — двух других просто нет.
    # `approved` остаётся, этап становится `validation`, хвост результата
    # сам зовёт дальше, и следующий вызов закрывает задачу. Двух шагов
    # из трёх никто не делал и никто не отменял.
    #
    # Сравниваем **число** шагов, а не состав: у шага нет идентификатора,
    # только `title`, и сверка по заголовкам прочитала бы переименование
    # как «удалили один, добавили другой» — утверждение слетало бы от любого
    # уточнения формулировки. Число шагов от переименования не меняется.
    #
    # И не запрет: описание инструмента прямо учит «передавай ВЕСЬ список»,
    # а случай (2) в нём — «человек попросил поправить план». Запрет оставил
    # бы попросившему убрать шаг один выход — `reset`, то есть потерю
    # и утверждения, и всех отметок. Тупиков не заводим.
    revoked = plan["approved"] and len(steps) < len(_steps(plan))
    fresh = {**plan, "steps": steps}
    if revoked:
        fresh["approved"] = False
    stage, current = stage_of(fresh)
    done = sum(1 for step in steps if step["status"] == "done")
    running = next(
        (i for i, step in enumerate(steps) if step["status"] == "in_progress"), None
    )
    head = (
        f"План записан: {len(steps)} шагов, сделано {done}, "
        + ("в работе: шаг %d." % (running + 1) if running is not None else "в работе: нет.")
    )
    tail = _TAILS.get(stage)
    if stage == "execution" and current is not None:
        tail = f"выполняй шаг {current + 1}"
    if revoked:
        # Снятое утверждение обязано быть **названо**: молча вернуть план
        # к ожиданию кнопки значило бы оставить модель ждать неизвестно чего.
        tail = "Шагов стало меньше, чем утверждал человек: план снова ждёт утверждения."
    # Результат — **всегда весь список**, а не «ок»: он возвращается модели
    # в контекст и работает её рабочей памятью по задаче. «Ок» сделал бы
    # инструмент отчётом для интерфейса, а инструмент обязан быть полезен
    # тому, кто его позвал.
    return fresh, f"{head}\n{plan_lines(fresh)}" + (f"\n{tail}" if tail else "")


def _finished(plan: dict, args) -> tuple[dict, str]:
    """`finish_task`: проверка сделанного.

    Зовётся только на `validation` — план утверждён и все шаги `done`, — и
    оба условия проверяются по отдельности: модель, позвавшая её раньше
    времени, обязана прочитать, чего именно не хватает.
    """
    if not plan.get("approved"):
        raise PlanError("план ещё не утверждён человеком, проверять нечего")
    steps = _steps(plan)
    unfinished = [step for step in steps if step.get("status") != "done"]
    if not steps or unfinished:
        raise PlanError(
            f"шагов не done: {len(unfinished) or len(steps)} — "
            "сначала сделай их и отметь через update_plan"
        )
    problems = (args or {}).get("problems")
    if not isinstance(problems, list):
        # Выход называется здесь, а не берётся общим: до этой причины
        # доходят только с утверждённым планом и всеми шагами `done`,
        # и общий выход посоветовал бы уже сделанное.
        raise PlanError(
            "problems прислан не списком, а перечень проблем обязателен",
            "позови finish_task заново и передай problems массивом строк; "
            "проблем нет — пустым массивом",
        )
    named = [str(item).strip() for item in problems if str(item).strip()]
    if named:
        # Флаг остаётся как был: задача не завершена, и следующий обмен
        # снова придёт на этап проверки. Проблемы не хранятся — они уезжают
        # модели в контекст, ей их и исправлять.
        listed = "; ".join(named)
        return plan, (
            f"Записано проблем: {len(named)}. Задача НЕ завершена. "
            f"Верни нужный шаг в pending через update_plan и исправь: {listed}"
        )
    return {**plan, "finished": True}, "Задача завершена. План больше не меняй."


def _approved(plan: dict) -> tuple[dict, str]:
    """`approve`: кнопка человека. Только на этапе `approval` — повторный
    отказан: «утверждено дважды» неотличимо от «утверждено не то»."""
    stage, _ = stage_of(plan)
    if stage != "approval":
        raise PlanError(f"утверждать нечего: этап сейчас {stage}, а не approval")
    fresh = {**plan, "approved": True}
    return fresh, f"План утверждён человеком.\n{plan_lines(fresh)}"


def _reopened(plan: dict) -> tuple[dict, str]:
    """`reopen`: человек переоткрывает завершённую задачу.

    Флаг снимается, шаги остаются `done` — этап становится `validation`:
    переоткрыли не для того, чтобы делать всё заново, а потому что в сделанном
    что-то не так. Обмен при этом **не отправляется**: что именно не так,
    человек напишет сам.
    """
    if not plan.get("finished"):
        raise PlanError("переоткрывать нечего: задача не завершена")
    fresh = {**plan, "finished": False}
    return fresh, f"Задача переоткрыта человеком.\n{plan_lines(fresh)}"


def _paused(plan: dict) -> tuple[dict, str]:
    """`pause`: человек приостанавливает работу.

    Только когда работа идёт: приостанавливать завершённую нечего, а
    повторная пауза неотличима от «пауза не сработала».
    """
    if plan.get("paused"):
        raise PlanError("задача уже на паузе")
    if plan.get("finished"):
        raise PlanError("задача завершена, приостанавливать нечего")
    fresh = {**plan, "paused": True}
    return fresh, f"Работа приостановлена человеком.\n{plan_lines(fresh)}"


def _resumed(plan: dict) -> tuple[dict, str]:
    """`resume`: человек снимает паузу.

    Снимает **только флажок** и больше ничего не трогает — и этого довольно,
    чтобы этап вернулся тот же, что был до паузы: он вычисляется из списка,
    а список не менялся. Помнить, куда возвращаться, поэтому не нужно
    и негде.
    """
    if not plan.get("paused"):
        raise PlanError("задача не на паузе, снимать нечего")
    fresh = {**plan, "paused": False}
    return fresh, f"Пауза снята человеком.\n{plan_lines(fresh)}"


def _reset(plan: dict) -> tuple[dict, str]:
    """`reset`: план целиком в пусто — пустой список и **все три флажка**
    сняты.

    Законен всегда: это действие человека, и на нём держится и «начать другую
    задачу», и «вернуться в обычный чат». Сняты именно все три — оставленный
    флажок сделал бы свежий план утверждённым, завершённым или стоящим
    на паузе, то есть соврал бы про этап с первого же сообщения.
    """
    return empty(), "Задача сброшена человеком: плана больше нет."


ALLOWED = {
    "update_plan": "перепиши список шагов целиком через update_plan",
    "finish_task": "дождись, когда план утвердят и все шаги будут done",
    "approve": "утверждать можно только план, который ждёт утверждения",
    "reopen": "переоткрыть можно только завершённую задачу",
    "pause": "приостановить можно только незавершённую работу",
    "resume": "снять паузу можно только с приостановленной задачи",
    "reset": "сбросить задачу можно всегда",
}
"""Что допустимо вместо отказанного — по действию. Часть формулы отказа,
и она обязана называть выход: директива без выхода оставляет модель
в тупике, а тупик она обходит объявлением успеха.

Имя без подчёркивания: таблица входит в **договор** — формулу отказа
цитирует CLAUDE.md, и проверка спрашивает у отказа дословный выход
из неё, а не пересказ. Причина при этом вправе назвать свой выход сама
(см. `PlanError`), и тогда берётся он."""


def apply(plan, action: str, args=None) -> tuple[dict, str]:
    """**Единственный источник истины переходов** — один и на инструмент,
    и на ручку.

    Действий семь: `update_plan` и `finish_task` зовёт модель, `approve`,
    `reopen`, `pause`, `resume` и `reset` — человек кнопкой. Второй проверки
    переходов рядом не заводить: две копии правил расходятся молча, и тогда
    кнопка разрешает то, что инструменту запрещено.

    Паузу ни один инструмент модели не трогает — ни поставить, ни снять:
    пауза это распоряжение человека, а распоряжений из разговора агент
    не выводит. Довод тот же, по которому он не пишет ни в профиль,
    ни в долговременную память.

    Отдаёт `(новый план, текст)`; отказ — `PlanError`, и внутри него готовая
    директива модели, а не код ошибки. Присланный план не меняется ни в одном
    исходе: новый собирается копией, и записывает его вызывающий — сам `apply`
    в базу не ходит вовсе.
    """
    plan = plan if isinstance(plan, dict) else empty()
    plan = {
        "steps": _steps(plan),
        "approved": bool(plan.get("approved")),
        "finished": bool(plan.get("finished")),
        "paused": bool(plan.get("paused")),
    }
    if action not in ALLOWED:
        raise PlanError(
            refusal(
                action, plan, "такого инструмента нет",
                f"звать можно {', '.join(TOOL_NAMES)}",
            )
        )
    # Приостановленную и завершённую задачу не меняет ни один инструмент
    # модели: и то и другое — распоряжение человека, и снимает его человек
    # кнопкой. Условие стоит **до** разбора аргументов: отказ не зависит
    # от того, что именно модель прислала.
    #
    # Пауза держится здесь, а не на правиле в промпте: правило объясняет,
    # а гарантирует код. «Продолжай» в чате перевесило бы любую просьбу,
    # и приостановленная задача поехала бы дальше.
    if action in ("update_plan", "finish_task"):
        if plan["paused"]:
            raise PlanError(
                refusal(
                    action,
                    plan,
                    "задача на паузе",
                    "дождаться, пока человек снимет паузу",
                )
            )
        if plan["finished"]:
            raise PlanError(
                refusal(
                    action,
                    plan,
                    "задача уже завершена",
                    "менять план может только человек, кнопкой «Переоткрыть»",
                )
            )
    try:
        if action == "update_plan":
            return _updated(plan, args)
        if action == "finish_task":
            return _finished(plan, args)
        if action == "approve":
            return _approved(plan)
        if action == "reopen":
            return _reopened(plan)
        if action == "pause":
            return _paused(plan)
        if action == "resume":
            return _resumed(plan)
        return _reset(plan)
    except PlanError as exc:
        # Причину называют помощники, а директиву собирает одно место: имя
        # действия и текущий план известны здесь, и вторая копия формулы
        # отказа разошлась бы с первой молча.
        raise PlanError(
            refusal(action, plan, exc.reason, exc.allowed or ALLOWED[action])
        ) from None
