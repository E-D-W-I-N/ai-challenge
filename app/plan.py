"""Состояние задачи: **план и есть состояние**.

Хранится один список шагов со статусами и три флажка — утверждён ли план,
завершена ли задача и приостановлена ли работа. Всё остальное, чего просит задание дня — этап задачи,
текущий шаг, ожидаемое действие, — из этого списка **вычисляется**
(`stage_of`), а не хранится рядом. Ничего не хранится дважды: ярлык этапа,
живущий рядом с работой, расходится с работой молча, и двигать его модели
приходится наугад.

Модуль нарочно без состояния: чистые функции над словарём. План лежит
у агента (`Agent.plan`) и в базе (`task_state`, `task_steps`), а здесь —
только правила переходов и то, как план выглядит для модели.
"""

from __future__ import annotations

STEP_STATUSES = ("pending", "in_progress", "done")
"""Что бывает с шагом: не начат, в работе, сделан. Три значения, и они же
стоят в `enum` описания инструмента: модель выбирает из того же списка,
из которого проверяет код."""

STAGES = ("planning", "approval", "execution", "validation", "done", "paused")
"""Этапы задачи в порядке прохождения — и `paused` последним, потому что
в прохождении его нет вовсе: пауза ложится **поверх** любого этапа. Ни один
из них не хранится: этап — это ответ `stage_of` по списку шагов и трём
флажкам."""


def empty() -> dict:
    """Пустое состояние задачи: план, которого ещё нет.

    Флажки здесь, а не вычисляются: «план утверждён» обязано пережить возврат
    шага в `pending`, иначе одна найденная проверкой проблема откатывала бы
    задачу к утверждению плана.

    Флажков три, и третий — пауза. Поля «с какого этапа приостановлено»
    рядом с ним **нет намеренно**: этап у нас вычисляется из списка, и пауза
    ничего не затирает — сняли флажок, и этап восстановился сам, потому что
    список не менялся. Хранись этап, пауза затёрла бы его, и пришлось бы
    помнить, куда возвращаться, то есть завести второй источник истины там,
    где его нет.
    """
    return {"steps": [], "approved": False, "finished": False, "paused": False}


def _steps(plan) -> list[dict]:
    """Шаги плана списком — и пустой список у чего угодно кривого. Читают
    этот модуль и ручки, и инструмент, и подъём из базы: падать на чужой
    форме нельзя, разговор дороже."""
    steps = (plan or {}).get("steps")
    return [step for step in steps if isinstance(step, dict)] if isinstance(steps, list) else []


def current_step(plan) -> int | None:
    """Номер текущего шага (с нуля) — или `None`, если текущего нет.

    Текущий — тот, что `in_progress`; его нет (свежий план «все pending»,
    модель забыла отметить) — первый не-`done`. Одно место на оба правила:
    второе, посчитанное иначе, назвало бы в промпте не тот шаг, который
    назвал бы интерфейс.
    """
    steps = _steps(plan)
    for index, step in enumerate(steps):
        if step.get("status") == "in_progress":
            return index
    for index, step in enumerate(steps):
        if step.get("status") != "done":
            return index
    return None


def stage_of(plan) -> tuple[str, int | None]:
    """Этап задачи и номер текущего шага — **единственное** место, где этап
    вычисляется.

    Разбор упорядоченный, а не поиск по таблице, и это не стиль: условия
    этапов **пересекаются**. План неутверждённый, но со всеми шагами `done`
    подходит и под `approval`, и под `validation` сразу — достижимо это
    просто, модель присылает план и, не дожидаясь кнопки, вторым
    `update_plan` ставит шагам `done`; кода, который бы ей это запретил,
    нет. Пойди разбор по `validation`, правило велело бы звать `finish_task`,
    а он при неутверждённом плане отказан, и кнопка «Утвердить» ответила бы
    409 ровно там, где человек обязан мочь утвердить.

    Поэтому порядок задан явно и сверху вниз:

    * `paused` → `paused`;
    * `finished` → `done`;
    * шагов нет → `planning`;
    * не `approved` → `approval`;
    * утверждён и **все** шаги `done` → `validation`;
    * иначе (утверждён, что-то не сделано) → `execution`.

    `validation` названа условием, а не остатком порядка: «утверждён и всё
    сделано» — это её смысл, и держаться он обязан на словах, а не на том,
    что ветка стоит последней.

    Пауза стоит **первой строкой**: приостановленная задача остаётся
    приостановленной, каким бы ни был список. `current` при паузе считается
    как обычно: человек обязан видеть, на каком шаге его остановили.

    А вот «на паузе и завершена одновременно» — состояние **недостижимое**,
    и обещать про него поведение здесь нечего: `pause` отказан при
    `finished`, а `finish_task`, `approve` и `reopen` отказаны при `paused`
    (`apply`). Порядок этих двух строк поэтому **оборонительный**: он ничего
    не решает сегодня и нужен затем, чтобы состояние, собранное чужой
    версией сервера или будущим действием, читалось определённо, а не
    как повезёт. Мутация «`finished` перевешивает `paused`» зелёная именно
    по этой причине, и это не пробел в проверке, а свойство продукта.
    """
    steps = _steps(plan)
    current = current_step(plan)
    if (plan or {}).get("paused"):
        return "paused", current
    if (plan or {}).get("finished"):
        return "done", current
    if not steps:
        return "planning", None
    if not (plan or {}).get("approved"):
        return "approval", current
    if all(step.get("status") == "done" for step in steps):
        return "validation", current
    return "execution", current


_MARKS = {"done": "[x]", "in_progress": "[>]"}
"""Чем помечен шаг в списке для модели. Неизвестный статус — пустая рамка:
план в базу пишет только `apply`, но читается он и из файла, который завела
чужая версия."""


def plan_lines(plan) -> str:
    """План так, как его **видит модель**, — одной картой и в блоке промпта,
    и в результате инструмента.

        план утверждён: да
        1. [x] собрать требования
        2. [>] схема базы ← в работе
        3. [ ] экран оплаты

    Без шагов — `шагов ещё нет`; у завершённой задачи добавляется строка
    `задача завершена: да`, у приостановленной — `задача на паузе: да`.

    Одна функция на оба места намеренно: две формы одного списка разъехались
    бы молча — модель читала бы в блоке одно, а в ответе на свой же вызов
    другое, и верить перестала бы обоим. Номера шагов здесь **с единицы**:
    их называет правило этапа, и человеку с моделью удобнее считать от одного.
    """
    approved = bool((plan or {}).get("approved"))
    lines = ["план утверждён: " + ("да" if approved else "нет")]
    if (plan or {}).get("finished"):
        lines.append("задача завершена: да")
    # Пауза названа и здесь, а не только в правиле этапа: модель обязана
    # видеть её и в блоке задачи, и в тексте любого отказа — отказ отдаёт
    # план этой же функцией.
    if (plan or {}).get("paused"):
        lines.append("задача на паузе: да")
    steps = _steps(plan)
    if not steps:
        lines.append("шагов ещё нет")
        return "\n".join(lines)
    for index, step in enumerate(steps, start=1):
        status = step.get("status")
        mark = _MARKS.get(status, "[ ]")
        tail = " ← в работе" if status == "in_progress" else ""
        lines.append(f"{index}. {mark} {step.get('title', '')}{tail}")
    return "\n".join(lines)


